/**
 * Pin the six split-topology operator claims from issue #1456 against shipped docs and
 * the code paths those docs name.
 *
 * Each cell is a source/docs contract, not a live fleet: the triage already classified
 * product ownership of #773 / #1332 / #1417 separately. This suite fails if a later edit
 * drops the generated-conf path, the log location, --host boot-vs-refresh, torn-pairing
 * pidfile vs pin coordinates, standalone deliver as a non-repair, or the example-unit
 * cgroup tradeoff.
 *
 * Run: pnpm smoke:split-topology-docs
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

const REPO = join(import.meta.dirname, "..", "..");
const read = (rel: string): string => readFileSync(join(REPO, rel), "utf8");

let pass = 0;
let fail = 0;
const check = (name: string, condition: boolean, detail?: unknown): void => {
  if (condition) {
    pass++;
    console.log(`  ✓ ${name}`);
  } else {
    fail++;
    console.log(`  ✗ FAIL: ${name}`, detail ?? "");
  }
};

const runAMesh = read("docs/run-a-mesh.md");
const cli = read("docs/cli.md");
const config = read("docs/config.md");
const control = read("docs/control-surface.md");
const delivery = read("docs/delivery-daemon.md");
const pid = read("packages/workspace/src/pid.ts");
const provision = read("packages/core/src/provision.ts");
const up = read("implementations/cli/src/commands/up.ts");
const deliveryProc = read("implementations/cli/src/lib/delivery-proc.ts");
const authPaths = read("packages/workspace/src/auth-paths.ts");
const localProcess = read("packages/workspace/src/local-process.ts");
const systemd = read("implementations/cli/src/lib/systemd-supervision.ts");
const upReport = read("implementations/cli/src/lib/up-report.ts");
const managerProc = read("implementations/cli/src/lib/manager-proc.ts");
const supervise = read("implementations/manager/src/commands.ts");

// ── 1. generated server.conf path + --host boot vs live refresh ──────────────
check(
  "claim 1: authDir is projectRoot/.cotal/auth",
  /export function authDir\(root: string\): string \{\n  return join\(root, "\.cotal", "auth"\);\n\}/.test(authPaths),
);
check(
  "claim 1: renderer marks server.conf generated and not hand-edited",
  provision.includes("# Generated by \\`cotal up\\` - do not edit by hand."),
);
check(
  "claim 1: default bind is loopback",
  /const host = values\.host \?\? "127\.0\.0\.1";/.test(up) && provision.includes('const host = opts.host ?? "127.0.0.1"'),
);
check(
  "claim 1: docs say live refresh does not rebind and hand-edit is not the fix",
  runAMesh.includes("`--host` is a boot flag, not a live rebind") &&
    runAMesh.includes("Do not edit `server.conf`") &&
    cli.includes("A live refresh (`✓ mesh already running`) does not rewrite `.cotal/auth/server.conf`") &&
    config.includes("<projectRoot>/.cotal/auth/server.conf") &&
    config.includes("A live refresh does not rewrite this file"),
);
check(
  "claim 1: live already-running path does not rewrite broker config",
  up.includes("No broker config is (re)written"),
);

// ── 2. up always starts a manager; split is topology, not singleton ──────────
check(
  "claim 2: operator guide names the split (up then down manager, supervise --server)",
  runAMesh.includes("There is no broker-only `up`") &&
    runAMesh.includes("cotal down manager") &&
    runAMesh.includes("cotal supervise --space main --server") &&
    cli.includes("There is no broker-only mode") &&
    control.includes("Only one manager per space") &&
    control.includes("cotal supervise"),
);
check(
  "claim 2: wait signal is detach stdout, not supervise's manager-up line",
  runAMesh.includes("Wait for `✓ running in the background:` with `manager` listed") &&
    runAMesh.includes("manager pidfile is live") &&
    runAMesh.includes("is not `✓ manager up`") &&
    runAMesh.includes("`.cotal/manager.<spaceKey>.log`") &&
    !runAMesh.includes("Wait for `✓ manager up`") &&
    !runAMesh.includes("`cotal status --components` to report `manager serving`") &&
    cli.includes("wait for `cotal up --detach` to") &&
    cli.includes("print `✓ running in the background:` with `manager` listed") &&
    cli.includes("pidfile liveness, not `✓ manager up`") &&
    control.includes("after `✓ running in the background:` lists"),
);
check(
  "claim 2: detach summary and ensureManager are pidfile-live; supervise prints manager up after start",
  upReport.includes("return `✓ running in the background: ${components.join(\", \")} - stop with: cotal down`;") &&
    managerProc.includes('if (state === "alive") return { running: true }') &&
    /startManagerDetached\(o\);\n  return \{ running: true \};/.test(managerProc) &&
    supervise.includes('await mgr.start();') &&
    supervise.includes('c.green("✓ manager up")'),
);

// ── 3. project-local file logs, not the unit journal ─────────────────────────
check(
  "claim 3: log templates are project .cotal delivery.<space> / manager.<space>",
  localProcess.includes('export const MANAGER_LOGFILE = "manager.{space}.log"') &&
    localProcess.includes('export const DELIVERY_LOGFILE = "delivery.{space}.log"'),
);
check(
  "claim 3: detached delivery redirects stdio onto the logfile",
  /stdio: \["ignore", fd, fd\]/.test(deliveryProc),
);
check(
  "claim 3: docs name project logs and empty journalctl for a oneshot wrapper",
  runAMesh.includes("Those files live under the **project** `.cotal/`, not `~/.cotal`") &&
    runAMesh.includes("`journalctl -u <unit>` can be empty") &&
    delivery.includes("does not put those lines in that unit's journal"),
);

// ── 4. standalone deliver is not a split-host repair ─────────────────────────
check(
  "claim 4: CLI and operator guide refuse standalone deliver as the split repair",
  cli.includes("is not an independent repair") &&
    /the manager and\n?the daemon must address one credential store/.test(cli) &&
    runAMesh.includes("is not a repair for that split") &&
    runAMesh.includes("manager root A writing and the daemon reloading root B"),
);

// ── 5. torn pairing names both pids; pin delete is not recovery ──────────────
check(
  "claim 5: torn-pairing NEXT names pidfile pid and pin pid",
  pid.includes("inspect both the pidfile pid and the pin pid") &&
    pid.includes("do not delete the identity pin") &&
    pid.includes("proven death of the pidfile target") &&
    pid.includes("names pid ${verdict.pinPid}, not the pidfile's pid"),
);
check(
  "claim 5: down docs match the NEXT coordinates and forbid pin deletion",
  cli.includes("The pidfile pid and the pin pid are two coordinates") &&
    cli.includes("Do not delete `<pidfile>.identity`"),
);

// ── 6. example units, not a shipped installer; cgroup trade is ownership ─────
check(
  "claim 6: warning still points at Supervising the detached stack",
  systemd.includes('export const DETACHED_SUPERVISION_DOC_SECTION = "Supervising the detached stack"'),
);
check(
  "claim 6: docs state no installer and the example-unit cgroup tradeoff",
  runAMesh.includes("no supported `cotal service install`") &&
    runAMesh.includes("examples of process models") &&
    runAMesh.includes("Type=simple") &&
    runAMesh.includes("nats in the unit's cgroup") &&
    runAMesh.includes("does not move nats out of that cgroup") &&
    runAMesh.includes("new process group, not a new systemd cgroup") &&
    runAMesh.includes("Neither trade is universal from") &&
    runAMesh.includes("`Type=simple` alone") &&
    runAMesh.includes("KillMode=control-group") &&
    runAMesh.includes("this CLI does not ship that escape") &&
    runAMesh.includes("`cotal status --components` liveness check, not a") &&
    runAMesh.includes("`--detach` launcher") &&
    !runAMesh.includes("nats is orphaned outside the cgroup") &&
    !runAMesh.includes("oneshot + `--detach` launcher"),
);

console.log(`SPLIT TOPOLOGY DOCS: ${pass}/${pass + fail}`);
process.exit(fail ? 1 : 0);
