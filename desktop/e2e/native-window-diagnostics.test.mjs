import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import test from 'node:test';
const source=readFileSync(new URL('./capture.ps1',import.meta.url),'utf8');
test('Windows census precedes the unique same-PID application-window selector',()=>{
 const census=source.slice(source.indexOf('public static Observation[] VisibleWindows'),source.indexOf("'@"));
 assert.match(census,/pid != target \|\| !IsWindowVisible\(window\)/);
 for(const field of ['handle=window.ToInt64()', 'title=title.ToString()', 'windowClass=windowClass.ToString()', 'left=bounds.Left', 'bottom=bounds.Bottom'])assert.ok(census.includes(field));
 assert.match(census,/return true;\s*\}, IntPtr.Zero\)/);
 assert.match(census,/if \(!EnumWindows\(/);
 assert.match(census,/throw new InvalidOperationException\("EnumWindows failed/);
 assert.doesNotMatch(census,/ShowWindow\(|SetForegroundWindow\(|PostMessage\(/);
 const observation=source.indexOf('$windowCensus = @()');
 const selected=source.indexOf('$window = [IntPtr][CotalWindow]::SelectApplicationWindow($windowCensus)');
 assert.ok(observation>0 && selected>observation);
 assert.ok(source.indexOf("'.windows.jsonl'")<selected);
 assert.match(source,/windows=\$windowCensus; error=\$windowCensusError/);
 assert.match(source,/SelectApplicationWindow\(\$windowCensus\)[\s\S]*?ShowWindow\(\$window, 9\)[\s\S]*?SetForegroundWindow\(\$window\)/);
 const selector=source.slice(source.indexOf('public static long SelectApplicationWindow'),source.indexOf("'@"));
 assert.match(selector,/row\.windowClass == "Tauri Window" && row\.boundsRead/);
 assert.match(selector,/width >= 560 && height >= 500 && width <= 4000 && height <= 4000/);
 assert.match(selector,/if \(count != 1\) throw/);
 assert.doesNotMatch(source,/\.MainWindowHandle/);
});
