$ErrorActionPreference = 'Stop'
if ($env:GITHUB_ACTIONS -ne 'true' -or $env:RUNNER_ENVIRONMENT -ne 'github-hosted') { throw 'Native updater validation is hosted-only.' }
$root = Join-Path $env:RUNNER_TEMP ('desktop-updater-compile-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $root | Out-Null
$key = Join-Path $root 'throwaway.key'
$out = Join-Path $env:RUNNER_TEMP 'desktop-updater-native'
New-Item -ItemType Directory -Path $out -Force | Out-Null
$prior = [Environment]::GetEnvironmentVariable('COTAL_UPDATER_PUBLIC_KEY', 'Process')
try {
  # Writing a key pair avoids the signer's stdout mode that prints private material.
  & pnpm --dir desktop exec tauri signer generate --ci --write-keys $key 1> (Join-Path $root 'signer.log') 2>&1
  if ($LASTEXITCODE -ne 0) { throw 'Throwaway updater key generation failed.' }
  if ($env:RUNNER_OS -ne 'Windows') {
    & chmod 600 $key "$key.pub"
    if ($LASTEXITCODE -ne 0) { throw 'Could not protect throwaway key.' }
  }
  $env:COTAL_UPDATER_PUBLIC_KEY = [IO.File]::ReadAllText("$key.pub").Trim()
  if (!$env:COTAL_UPDATER_PUBLIC_KEY) { throw 'Throwaway public key is empty.' }
  & pnpm --dir desktop exec tauri build --debug --no-bundle 1> (Join-Path $out 'configured.log') 2>&1
  if ($LASTEXITCODE -ne 0) { throw 'Configured updater branch did not compile. See configured.log.' }
  Remove-Item Env:COTAL_UPDATER_PUBLIC_KEY
  & pnpm --dir desktop exec tauri build --debug --no-bundle 1> (Join-Path $out 'no-key.log') 2>&1
  if ($LASTEXITCODE -ne 0) { throw 'No-key updater branch did not compile. See no-key.log.' }
  & cargo test --locked --manifest-path desktop/src-tauri/Cargo.toml --lib updater::disabled_tests 1> (Join-Path $out 'no-key-tests.log') 2>&1
  if ($LASTEXITCODE -ne 0) { throw 'No-key updater commands did not pass native tests.' }
  @{ schema = 1; configured = 'compiled'; noKey = 'compiled'; platform = $env:RUNNER_OS; source = $env:GITHUB_SHA; installed = $false } | ConvertTo-Json | Set-Content (Join-Path $out 'result.json')
} finally {
  if ($null -eq $prior) { Remove-Item Env:COTAL_UPDATER_PUBLIC_KEY -ErrorAction SilentlyContinue }
  else { $env:COTAL_UPDATER_PUBLIC_KEY = $prior }
  # Only material generated by this job, never an owner key or a published signing secret.
  foreach ($path in @($key, "$key.pub", (Join-Path $root 'signer.log'))) {
    if (Test-Path -LiteralPath $path) { Remove-Item -LiteralPath $path }
  }
}
