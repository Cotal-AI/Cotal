#!/usr/bin/env node
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { appendFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { packColdCandidate } from "./pack-cold-candidate.mjs";
import { publishColdCandidate } from "./publish-cold-candidate.mjs";
import { verifyPromotedArchives } from "./verify-promoted-archives.mjs";
import { coldOsEnvironment } from "./release-cold-environment.mjs";
import { publicationExecutionDeadline, remainingBudget } from "./publication-budget.mjs";

const env = process.env;
assert(env.GITHUB_EVENT_NAME === "workflow_dispatch" && env.GITHUB_REF === "refs/heads/main", "direct release requires a main dispatch");
assert(/^[a-f0-9]{40}$/.test(env.RELEASE_SOURCE ?? ""), "release source must be a full commit");
assert(/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(env.RELEASE_VERSION ?? ""), "release version is invalid");
const tag = env.RELEASE_TAG || "latest";
assert(/^[a-z][a-z0-9._-]*$/i.test(tag), "release tag is invalid");
const deadline = publicationExecutionDeadline(env.RELEASE_REQUESTED_AT, env.RELEASE_ATTEMPT_STARTED_AT);
const root = resolve(env.RELEASE_ROOT);
const git = args => execFileSync("git", args, { cwd: root, encoding: "utf8", timeout: remainingBudget(deadline) }).trim();
assert.equal(git(["rev-parse", "HEAD"]), env.RELEASE_SOURCE);
assert.equal(JSON.parse(readFileSync(join(root, "bin/package.json"), "utf8")).version, env.RELEASE_VERSION);
const home = join(env.RUNNER_TEMP, "release-build-home");
mkdirSync(home, { recursive: true, mode: 0o700 });
const buildEnv = { ...coldOsEnvironment(), HOME: home, XDG_CONFIG_HOME: home, XDG_CACHE_HOME: join(home, "cache"), npm_config_userconfig: join(home, ".npmrc"), npm_config_globalconfig: join(home, "global.npmrc") };
writeFileSync(buildEnv.npm_config_userconfig, "", { flag: "wx", mode: 0o600 });
writeFileSync(buildEnv.npm_config_globalconfig, "", { flag: "wx", mode: 0o600 });
const build = (file, args, options = {}) => execFileSync(file, args, { ...options, cwd: options.cwd ?? root, env: buildEnv, timeout: remainingBudget(deadline), stdio: options.encoding ? undefined : "inherit" });
build("pnpm", ["install", "--frozen-lockfile", "--ignore-scripts"]);
build("pnpm", ["build"]);
build(process.execPath, [join(root, "scripts/seat-assemble-natives.mjs"), "--x64", join(env.RUNNER_TEMP, "native/cold-native-x64/peercred.node"), "--arm64", join(env.RUNNER_TEMP, "native/cold-native-arm64/peercred.node")]);
execFileSync(process.execPath, [join(root, "scripts/workspace-assemble-natives.mjs")], { cwd: root, env: { ...buildEnv, WORKSPACE_NATIVE_X64: join(env.RUNNER_TEMP, "native/workspace-native-x64"), WORKSPACE_NATIVE_ARM64: join(env.RUNNER_TEMP, "native/workspace-native-arm64") }, timeout: remainingBudget(deadline), stdio: "inherit" });
const directory = join(env.RUNNER_TEMP, "direct-candidate");
const manifest = packColdCandidate({ root, output: directory, exec: build });
assert(manifest.packages.every(pkg => pkg.version === env.RELEASE_VERSION), "release packages are not version matched");
const receiptFile = join(env.RUNNER_TEMP, "publication.json");
await publishColdCandidate({ env, root, directory, receiptFile, qualificationRequired: false, tag });
const manifestFile = join(directory, "manifest.json");
const { createHash } = await import("node:crypto");
const expectedSha256 = createHash("sha256").update(readFileSync(manifestFile)).digest("hex");
const availability = await verifyPromotedArchives({ root, manifestFile, requestedAt: env.RELEASE_REQUESTED_AT, attemptStartedAt: env.RELEASE_ATTEMPT_STARTED_AT, expectedSha256, tag });
writeFileSync(join(env.RUNNER_TEMP, "registry-archives.json"), JSON.stringify(availability, null, 2) + "\n", { flag: "wx", mode: 0o600 });
appendFileSync(env.GITHUB_OUTPUT, `published=true\nversion=${env.RELEASE_VERSION}\nsource=${env.RELEASE_SOURCE}\n`);
console.log(`Published ${env.RELEASE_VERSION}; within original command budget=${availability.withinPublicationBudget}`);
