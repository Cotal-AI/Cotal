#!/usr/bin/env node
// Refuse AI attribution in commit messages and PR text.
//
// AGENTS.md ("Git and public messages") bans tool or AI attribution anywhere: no
// Co-Authored-By: Claude, no "Generated with" footers, no agent, seat or model identity in a
// commit, PR, issue or comment. Six commits on main since that rule carry it anyway (b6c843fb1:
// ten Co-Authored-By trailers; c9ea09136: two model ids in a reviewer sentence; four 2026-08-29
// commits with one trailer each), every one landed by a squash or merge that concatenates the
// constituent commit bodies, so the merger never typed them. This check reads every commit in the
// range, merges included, plus the PR title and body, which is exactly the material a squash body
// is built from, and fails closed on a CLOSED grammar:
//
//   trailer   Co-Authored-By / Signed-off-by / Generated-by / Assisted-by whose value names an
//             AI tool or vendor, or any address at anthropic.com / openai.com
//   footer    "Generated with <tool>", "Generated by <tool>", the robot-emoji footer
//   address   a mailbox at an AI vendor's domain anywhere in the text
//   seat      a fleet seat, worker or orchestrator name, matched on HOW such a name is BUILT:
//             an optional lane qualifier, a ROLE word, free qualifier segments, and at least one
//             SERIAL or model-family segment after the role
//   model     a model id (gpt-5.6-sol, grok-4.6, glm-5.3, gemini-3.8-flash, Claude Opus 5)
//
// The author and committer fields carry one more rule, `identity`, which the message body does
// not: see IDENTITY_RULES below.
//
// A product name is content, not attribution: "Claude Code" in the subject of a
// connector-claude-code fix passes (that is why the grammar is closed and does not match the
// bare word). A model id in a message is refused even when the change is about that model; put
// the id in the diff and write "the default model" in the message. Prose that quotes the
// forbidden footer (the AGENTS.md commit itself, 505125659) is refused too. This grader cannot
// read intent, so it does not try to: it is a detector over a closed grammar, and its false
// positives are cheap to reword while its false negatives are the ones that reach main.
//
// Usage:
//   node scripts/check-attribution.mjs --range <base>..<head> [--event <github-event.json>]
//   node scripts/check-attribution.mjs --selftest
//
// Exit 0 clean, 1 attribution found, 2 the check could not run (empty range, bad input): a
// range that yields no commits on a pull_request is a broken invocation, never a pass.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const AI_NAMES =
  /\b(claude|anthropic|openai|chatgpt|gpt|copilot|codex|gemini|grok|glm|cursor|windsurf|devin|aider|opencode|jcode|ai assistant|an ai|llm)\b/i;

// HOW A SEAT NAME IS BUILT, rather than a list of the seat names that exist today.
//
// The previous spelling of this rule was four literal alternatives (`rev|mgr` + digits, `rev|mgr`
// + a closed model list, `w|p2-impl|p2-review-[ab]`, `fm-mac-`). Every one of them named a naming
// CONVENTION, so the rule reported clean the moment the convention moved: `mgr-t0001`,
// `worker-w0003-task-r2` and `orchestrator-v0` are seat names of exactly the kind it exists to
// catch and it passed all three (#1560). A longer list of literals rots the same way, so the rule
// below is written against the two parts every such name actually has.
//
//   ROLE   what the seat DOES. A function word, which is what survives a renaming: a fleet is
//          renamed by changing prefixes and serial spellings, not by ceasing to have reviewers,
//          managers and workers.
//   TAG    what distinguishes one seat of that role from another: a SERIAL (a run of digits,
//          optionally with a short letter prefix or a single trailing letter), a version counter,
//          or a model family.
//
// A name is a seat when a ROLE segment is followed, anywhere later in the same token, by a TAG
// segment. Both `-` and `_` join segments, because a seat name that spells its joins with `_`
// is the same name. The leading qualifier is bounded to a short lane tag (`p2-impl-773-a2`) so
// an arbitrary English word in front of a role word cannot drag prose in.
const SEAT_ROLE =
  String.raw`(?:rev|review|reviewer|mgr|manager|orch|orchestrator|lane|fm|w|worker|impl|implementer|writer|verifier|critic|auditor|panel|seat|agent|coordinator|supervisor|runner)`;
const SEAT_TAG =
  String.raw`(?:\d{2,}[a-z]?|[a-z]{1,2}\d{3,}[a-z]?|v\d+|gpt|grok|glm|gemini|sol|opus|sonnet|haiku|claude|codex)`;
const SEAT_SEGMENT = String.raw`[a-z0-9]+`;
const SEAT_LANE = String.raw`(?:[a-z]{1,3}\d{1,3}[-_])?`;
const CONSTRUCTED_SEAT = new RegExp(
  String.raw`(^|[^\w/.-])${SEAT_LANE}${SEAT_ROLE}([-_]${SEAT_SEGMENT})*[-_]${SEAT_TAG}([-_]${SEAT_SEGMENT})*(?![\w.-])`,
  'i',
);

// The literal alternatives the construction rule does NOT subsume, kept so this change loses no
// name the check already caught. `fm-mac-<x>` is a host-bound legacy seat with no serial segment
// at all, so no construction rule can reach it without also reaching `seat-native-linux-x64`,
// a real package name in this repository. A legacy convention is a closed, finite set: naming it
// as legacy is honest, and it cannot grow.
const LEGACY_SEAT = /(^|[^\w/.-])fm-mac-[a-z][a-z0-9-]*\b/i;

export const RULES = [
  {
    id: 'trailer',
    describe: 'attribution trailer',
    test: (line) => {
      const m = /^\s*(co-authored-by|signed-off-by|generated-by|assisted-by|reviewed-by|authored-by)\s*:\s*(.+)$/i.exec(line);
      if (!m) return false;
      const value = m[2];
      return AI_NAMES.test(value) || /@(anthropic|openai)\.com/i.test(value);
    },
  },
  {
    id: 'footer',
    describe: 'generated-with footer',
    test: (line) =>
      /\bgenerated (with|by|using)\b.*\b(claude|copilot|codex|cursor|chatgpt|gpt|gemini|aider|opencode|jcode|ai)\b/i.test(line) ||
      /\u{1F916}/u.test(line),
  },
  {
    id: 'address',
    describe: 'AI vendor address',
    test: (line) => /\b[\w.+-]+@(anthropic|openai)\.com\b/i.test(line),
  },
  {
    id: 'seat',
    describe: 'fleet seat or orchestrator name',
    test: (line) => CONSTRUCTED_SEAT.test(line) || LEGACY_SEAT.test(line),
  },
  {
    id: 'model',
    describe: 'model id',
    test: (line) =>
      /(^|[^\w/.-])(gpt|grok|glm|gemini|claude)-\d+(\.\d+)?(-[a-z]+)*\b/i.test(line) ||
      /\bclaude\s+(opus|sonnet|haiku|fable|mythos)\s*\d/i.test(line) ||
      /\b(opus|sonnet|haiku|fable|mythos)-\d+(\.\d+)?\b/i.test(line),
  },
];

// THE AUTHOR AND COMMITTER FIELDS GET ONE EXTRA RULE, and it carries no role vocabulary at all.
//
// An automation identity in the author field of permanent history cannot be corrected after a
// merge without a rewrite, so that field is worth a second, independent reader. It can afford one
// the message body cannot: the whole field is the subject, so the rule can grade the SHAPE of the
// identity instead of hunting a token inside prose.
//
// A person's commit identity is a name. A seat's is a machine slug: lowercase segments joined by
// `-` or `_`, one of which distinguishes this seat from its siblings. So a display name that is
// entirely such a slug AND carries a serial, version or model-family segment is refused, whatever
// role word it happens to use. That is the half of this check that does not rot when the fleet is
// renamed, because it never learned what the fleet was called: `mgr-t0001` and a seat named after
// some function this file has never heard of are the same shape to it.
//
// Measured against every author and committer identity in this repository's history, the only
// identity it reports is an automation lane's, which is the identity it exists to refuse.
const IDENTITY_SLUG = /^[a-z][a-z0-9]*(?:[-_][a-z0-9]+)+$/i;
const IDENTITY_TAG = /^(?:[a-z]{0,3}\d+[a-z]?|v\d+|gpt|grok|glm|gemini|sol|opus|sonnet|haiku|claude|codex)$/i;

/** The display name of a `Name <mailbox>` identity line, without the mailbox. */
export function displayName(identity) {
  return String(identity ?? '').replace(/\s*<[^>]*>\s*$/, '').trim();
}

export const IDENTITY_RULES = [
  {
    id: 'identity',
    describe: 'machine identity in an author or committer field',
    test: (line) => {
      const name = displayName(line);
      if (!IDENTITY_SLUG.test(name)) return false;
      return name.split(/[-_]/).some((segment) => IDENTITY_TAG.test(segment));
    },
  },
];

// Fullwidth punctuation, confusable hyphens and non-breaking spaces are the cheap way to spell a
// trailer the grammar would otherwise refuse, so every line is folded to NFKC (fullwidth to ASCII)
// and every dash-like code point to "-" before a rule sees it. The reported text is the original.
const DASHES = /[\u2010-\u2015\u2212\u2E3A\u2E3B\uFE58\uFE63\uFF0D]/g;
export function normalize(line) {
  return line.normalize('NFKC').replace(DASHES, '-').replace(/[\u00A0\u2000-\u200B\u202F\u205F\u3000]/g, ' ');
}

export function findings(text, where, rules = RULES) {
  const out = [];
  const lines = String(text ?? '').split(/\r?\n/);
  lines.forEach((raw, i) => {
    const line = normalize(raw);
    for (const rule of rules) {
      if (rule.test(line)) out.push({ where, line: i + 1, rule: rule.id, describe: rule.describe, text: raw.trim() });
    }
  });
  return out;
}

function git(args) {
  return execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

// One record per commit: sha, author line, committer line, full message. Records are separated
// by RS (0x1e) and fields by US (0x1f) so a message containing newlines or NULs cannot split
// a record. Merge commits are graded like any other: a squash concatenates their bodies too, a
// merge-commit landing keeps them verbatim, and `--no-merges` was a reproduced bypass (a trailer
// in a "Merge branch" body passed the first version of this check).
const RS = '\x1e';
const US = '\x1f';

export function commitsInRange(range) {
  const raw = git(['log', `--format=%H%x1f%an <%ae>%x1f%cn <%ce>%x1f%B%x1e`, range]);
  return raw
    .split(RS)
    .map((s) => s.replace(/^\n/, ''))
    .filter((s) => s.trim().length > 0)
    .map((s) => {
      const [sha, author, committer, message] = s.split(US);
      return { sha, author, committer, message: message ?? '' };
    });
}

/** Rules applied to a commit's author and committer identity: the shared grammar plus the
 *  identity-shape reader that only makes sense when the whole field is one identity. */
export const IDENTITY_GRAMMAR = [...RULES, ...IDENTITY_RULES];

export function gradeCommits(commits) {
  const out = [];
  for (const c of commits) {
    const short = c.sha.slice(0, 9);
    out.push(...findings(c.message, `commit ${short} message`));
    out.push(...findings(c.author, `commit ${short} author`, IDENTITY_GRAMMAR).map((f) => ({ ...f, line: 0 })));
    out.push(...findings(c.committer, `commit ${short} committer`, IDENTITY_GRAMMAR).map((f) => ({ ...f, line: 0 })));
  }
  return out;
}

export function gradeEvent(eventPath) {
  if (!eventPath) return [];
  const ev = JSON.parse(readFileSync(eventPath, 'utf8'));
  const pr = ev.pull_request;
  if (!pr) return [];
  return [...findings(pr.title, 'PR title'), ...findings(pr.body, 'PR body')];
}

function report(all) {
  for (const f of all) {
    console.log(`${f.where}:${f.line}: ${f.describe} (${f.rule}): ${f.text}`);
  }
  console.log('');
  console.log(`attribution check: ${all.length} finding(s).`);
  console.log('AGENTS.md forbids AI attribution in commits, PRs, issues and comments. Reword the');
  console.log('message: drop the trailer or footer, name no seat or model, write "a panel reviewer"');
  console.log('or "the lane manager". A commit already on the branch needs an amend or a rebase -i;');
  console.log('the squash body is built from these messages, so fixing the PR body alone is not enough.');
}

