/** Grade one line and return the rule ids it produced. */
const rulesFor = (text, rules) => findings(text, 'fixture', rules).map((f) => f.rule);

function nameFixtures() {
  let failed = 0;
  for (const [why, seat] of SEAT_NAMES) {
    const got = rulesFor(seat, RULES);
    const ok = got.includes('seat');
    console.log(`${ok ? 'ok  ' : 'FAIL'} seat name alone (${why}): expected [seat] got [${got}]`);
    if (!ok) failed += 1;
  }
  for (const [why, identity, expect] of IDENTITY_FIXTURES) {
    const got = rulesFor(identity, IDENTITY_GRAMMAR);
    const ok = JSON.stringify(got) === JSON.stringify(expect);
    console.log(`${ok ? 'ok  ' : 'FAIL'} identity field (${why}): expected [${expect}] got [${got}]`);
    if (!ok) failed += 1;
  }
  // The identity rule must stay OFF the message body: a commit that discusses `mgr-t0001` in prose
  // is a seat finding, never an identity finding, or the extra rule would double every report.
  const body = rulesFor('mgr-t0001 <seat@example.invalid>', RULES);
  const ok = !body.includes('identity');
  console.log(`${ok ? 'ok  ' : 'FAIL'} the identity rule is scoped to identity fields: got [${body}]`);
  if (!ok) failed += 1;
  return failed;
}

// The merge-commit bypass, reproduced as a git fixture: two clean commits and a merge whose body
// carries a trailer. `git log --no-merges` made that body invisible to the first version.
function gitFixtureSelftest() {
  const dir = mkdtempSync(join(tmpdir(), 'attribution-selftest-'));
  const env = {
    ...process.env,
    GIT_AUTHOR_NAME: 'Fixture', GIT_AUTHOR_EMAIL: 'fixture@example.org',
    GIT_COMMITTER_NAME: 'Fixture', GIT_COMMITTER_EMAIL: 'fixture@example.org',
  };
  const g = (...args) => execFileSync('git', args, { cwd: dir, env, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  try {
    g('init', '-q', '-b', 'main');
    writeFileSync(join(dir, 'a'), 'a\n'); g('add', 'a'); g('commit', '-q', '-m', 'base');
    g('checkout', '-q', '-b', 'topic');
    writeFileSync(join(dir, 'b'), 'b\n'); g('add', 'b'); g('commit', '-q', '-m', 'feat: clean one');
    g('checkout', '-q', 'main');
    writeFileSync(join(dir, 'c'), 'c\n'); g('add', 'c'); g('commit', '-q', '-m', 'chore: clean two');
    g('checkout', '-q', 'topic');
    g('merge', '-q', '--no-ff', '-m', 'Merge main into topic\n\nCo-Authored-By: Claude Code <noreply@anthropic.com>', 'main');
    const base = g('rev-parse', 'main').trim();
    const head = g('rev-parse', 'topic').trim();
    const saved = process.cwd();
    process.chdir(dir);
    try {
      const commits = commitsInRange(`${base}..${head}`);
      const got = gradeCommits(commits).map((f) => f.rule);
      const expect = ['trailer', 'address'];
      const ok = commits.length === 2 && JSON.stringify(got) === JSON.stringify(expect);
      console.log(`${ok ? 'ok  ' : 'FAIL'} merge commit body graded: ${commits.length} commit(s) in range, expected [${expect}] got [${got}]`);
      return ok;
    } finally {
      process.chdir(saved);
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

export function selftest() {
  let failed = 0;
  for (const c of SELFTEST) {
    const got = findings(c.text, c.name).map((f) => f.rule);
    const ok = JSON.stringify(got) === JSON.stringify(c.expect);
    console.log(`${ok ? 'ok  ' : 'FAIL'} ${c.name}: expected [${c.expect}] got [${got}]`);
    if (!ok) failed += 1;
  }
  failed += nameFixtures();
  if (!gitFixtureSelftest()) failed += 1;
  const total = SELFTEST.length + SEAT_NAMES.length + IDENTITY_FIXTURES.length + 2;
  console.log(`selftest: ${total - failed}/${total} fixtures graded as expected`);
  return failed === 0;
}

function main(argv) {
  const args = argv.slice(2);
  const get = (flag) => {
    const i = args.indexOf(flag);
    return i >= 0 ? args[i + 1] : undefined;
  };
  if (args.includes('--selftest')) return selftest() ? 0 : 2;
  const range = get('--range');
  const eventPath = get('--event');
  if (!range && !eventPath) {
    console.error('usage: check-attribution.mjs --range <base>..<head> [--event <event.json>] | --selftest');
    return 2;
  }
  const all = [];
  let commits = [];
  if (range) {
    commits = commitsInRange(range);
    if (commits.length === 0 && !args.includes('--allow-empty')) {
      console.error(`attribution check: range ${range} yields no commits; refusing to report a pass on nothing.`);
      return 2;
    }
    all.push(...gradeCommits(commits));
  }
  all.push(...gradeEvent(eventPath));
  console.log(
    `attribution check: ${commits.length} commit(s) in ${range ?? '(no range)'}${eventPath ? ', plus PR title and body' : ''}`,
  );
  if (all.length === 0) {
    console.log('attribution check: clean.');
    return 0;
  }
  report(all);
  return 1;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.exit(main(process.argv));
}
