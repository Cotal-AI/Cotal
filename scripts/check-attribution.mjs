#!/usr/bin/env node
// Refuse AI attribution in commit messages and PR text.
//
// AGENTS.md ("Git and public messages") bans tool or AI attribution anywhere: no
// Co-Authored-By: Claude, no "Generated with" footers, no agent, seat or model identity in a
// commit, PR, issue or comment. Two commits on main carry it anyway (b6c843fb1: ten
// Co-Authored-By trailers; c9ea09136: two model ids in a reviewer sentence), and both arrived
// through a squash merge that concatenates every constituent commit body, so the merger never
// typed them. This check reads the constituent commits, the PR title and the PR body, which is
// exactly the material the squash body is built from, and fails closed on a CLOSED grammar:
//
//   trailer   Co-Authored-By / Signed-off-by / Generated-by / Assisted-by whose value names an
//             AI tool or vendor, or any address at anthropic.com / openai.com
//   footer    "Generated with <tool>", "Generated by <tool>", the robot-emoji footer
//   address   a mailbox at an AI vendor's domain anywhere in the text
//   seat      a fleet seat or orchestrator name (rev-<n>-<family>, mgr-<n>-<lane>, fm-mac-<x>)
//   model     a model id (gpt-5.6-sol, grok-4.6, glm-5.3, gemini-3.8-flash, Claude Opus 5)
//
// A product name is content, not attribution: "Claude Code" in the subject of a
// connector-claude-code fix passes (that is why the grammar is closed and does not match the
// bare word). A model id in a message is refused even when the change is about that model; put
// the id in the diff and write "the default model" in the message. This grader cannot read
// intent, so it does not try to.
//
// Usage:
//   node scripts/check-attribution.mjs --range <base>..<head> [--event <github-event.json>]
//   node scripts/check-attribution.mjs --selftest
//
// Exit 0 clean, 1 attribution found, 2 the check could not run (empty range, bad input): a
// range that yields no commits on a pull_request is a broken invocation, never a pass.

import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

const AI_NAMES =
  /\b(claude|anthropic|openai|chatgpt|gpt|copilot|codex|gemini|grok|glm|cursor|windsurf|devin|aider|opencode|jcode|ai assistant|an ai|llm)\b/i;

export const RULES = [
  {
    id: 'trailer',
    describe: 'attribution trailer',
    test: (line) => {
      const m = /^\s*(co-authored-by|signed-off-by|generated-by|assisted-by|reviewed-by|authored-by)\s*:\s*(.+)$/i.exec(line);
      if (!m) return false;
      const value = m[2];
      return AI_NAMES.test(value) || /@(anthropic|openai)\.com/i.test(value);
    },
  },
  {
    id: 'footer',
    describe: 'generated-with footer',
    test: (line) =>
      /\bgenerated (with|by|using)\b.*\b(claude|copilot|codex|cursor|chatgpt|gpt|gemini|aider|opencode|jcode|ai)\b/i.test(line) ||
      /\u{1F916}/u.test(line),
  },
  {
    id: 'address',
    describe: 'AI vendor address',
    test: (line) => /\b[\w.+-]+@(anthropic|openai)\.com\b/i.test(line),
  },
  {
    id: 'seat',
    describe: 'fleet seat or orchestrator name',
    test: (line) =>
      /(^|[^\w/.-])(rev|mgr)-\d+[a-z]?(-[a-z0-9]+)+\b/i.test(line) ||
      /(^|[^\w/.-])fm-mac-[a-z][a-z0-9-]*\b/i.test(line),
  },
  {
    id: 'model',
    describe: 'model id',
    test: (line) =>
      /(^|[^\w/.-])(gpt|grok|glm|gemini|claude)-\d+(\.\d+)?(-[a-z]+)*\b/i.test(line) ||
      /\bclaude\s+(opus|sonnet|haiku|fable|mythos)\s*\d/i.test(line) ||
      /\b(opus|sonnet|haiku|fable|mythos)-\d+(\.\d+)?\b/i.test(line),
  },
];

export function findings(text, where) {
  const out = [];
  const lines = String(text ?? '').split(/\r?\n/);
  lines.forEach((line, i) => {
    for (const rule of RULES) {
      if (rule.test(line)) out.push({ where, line: i + 1, rule: rule.id, describe: rule.describe, text: line.trim() });
    }
  });
  return out;
}

function git(args) {
  return execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

// One record per commit: sha, author line, committer line, full message. Records are separated
// by RS (0x1e) and fields by US (0x1f) so a message containing newlines or NULs cannot split
// a record.
const RS = '\x1e';
const US = '\x1f';

export function commitsInRange(range) {
  const raw = git(['log', '--no-merges', `--format=%H%x1f%an <%ae>%x1f%cn <%ce>%x1f%B%x1e`, range]);
  return raw
    .split(RS)
    .map((s) => s.replace(/^\n/, ''))
    .filter((s) => s.trim().length > 0)
    .map((s) => {
      const [sha, author, committer, message] = s.split(US);
      return { sha, author, committer, message: message ?? '' };
    });
}

export function gradeCommits(commits) {
  const out = [];
  for (const c of commits) {
    const short = c.sha.slice(0, 9);
    out.push(...findings(c.message, `commit ${short} message`));
    out.push(...findings(c.author, `commit ${short} author`).map((f) => ({ ...f, line: 0 })));
    out.push(...findings(c.committer, `commit ${short} committer`).map((f) => ({ ...f, line: 0 })));
  }
  return out;
}

export function gradeEvent(eventPath) {
  if (!eventPath) return [];
  const ev = JSON.parse(readFileSync(eventPath, 'utf8'));
  const pr = ev.pull_request;
  if (!pr) return [];
  return [...findings(pr.title, 'PR title'), ...findings(pr.body, 'PR body')];
}

function report(all) {
  for (const f of all) {
    console.log(`${f.where}:${f.line}: ${f.describe} (${f.rule}): ${f.text}`);
  }
  console.log('');
  console.log(`attribution check: ${all.length} finding(s).`);
  console.log('AGENTS.md forbids AI attribution in commits, PRs, issues and comments. Reword the');
  console.log('message: drop the trailer or footer, name no seat or model, write "a panel reviewer"');
  console.log('or "the lane manager". A commit already on the branch needs an amend or a rebase -i;');
  console.log('the squash body is built from these messages, so fixing the PR body alone is not enough.');
}

// The two real leaks and the known false positive, held here so the grader proves its own
// grammar before it grades anything. Every refused fixture is a message a merge on main carried
// or a harness default; every passing fixture is prose a human contributor would write.
const SELFTEST = [
  {
    name: 'b6c843fb1 trailer (#1350)',
    text: 'fix(runtime)!: isolate workflow driver authority (#1350)\n\nbody\n\nCo-Authored-By: Claude Code <noreply@anthropic.com>\n\nmore\n\nCo-authored-by: Claude Code <noreply@anthropic.com>',
    expect: ['trailer', 'address', 'trailer', 'address'],
  },
  {
    name: 'c9ea09136 model ids (#1419)',
    text: "Reviewed at exact head c63d2f401b574392a4cf0c716212f83217283414 by two independent cross-vendor reviewers (gpt-5.6-sol and grok-4.6), both APPROVE, model identity verified from each seat's connector log.",
    expect: ['model'],
  },
  {
    name: 'harness default trailer',
    text: 'feat: x\n\nCo-Authored-By: Claude Opus 5 (1M context) <noreply@anthropic.com>',
    expect: ['trailer', 'address', 'model'],
  },
  {
    name: 'harness PR footer',
    text: 'Summary\n\n\u{1F916} Generated with [Claude Code](https://claude.com/claude-code)',
    expect: ['footer'],
  },
  {
    name: 'seat names',
    text: 'Following discussion with rev-1429-gpt and mgr-1356-presence, and fm-mac-orch-recovered agreed. Worktree /home/cotal/wt/rev-401r-sol-c.',
    expect: ['seat'],
  },
  {
    name: 'gemini flash and glm',
    text: 'Verdicts from gemini-3.8-flash and glm-5.3 were APPROVE.',
    expect: ['model'],
  },
  {
    name: 'f4672fd2b product name (#1416) passes',
    text: 'fix(connector-claude-code): list marketplace plugins as objects with a source (#1416)\n\n`cotal setup` generated `.claude-plugin/marketplace.json` with `plugins` as bare names. Claude\nCode 2.1.267 rejects both. Reproduced first-hand on Claude Code 2.1.267.',
    expect: [],
  },
  {
    name: 'human co-author passes',
    text: 'fix: thing\n\nCo-authored-by: Jane Doe <jane@example.org>',
    expect: [],
  },
  {
    name: 'hyphenated words that are not seats pass',
    text: 'docs: rev-2 of the prev-1 layout; see path/rev-3-gpt/file and version-mgr-4.',
    expect: [],
  },
  {
    name: 'a panel reviewer phrasing passes',
    text: 'Reviewed at exact head by two independent panel reviewers, both APPROVE; the lane manager folded it.',
    expect: [],
  },
];

export function selftest() {
  let failed = 0;
  for (const c of SELFTEST) {
    const got = findings(c.text, c.name).map((f) => f.rule);
    const ok = JSON.stringify(got) === JSON.stringify(c.expect);
    console.log(`${ok ? 'ok  ' : 'FAIL'} ${c.name}: expected [${c.expect}] got [${got}]`);
    if (!ok) failed += 1;
  }
  console.log(`selftest: ${SELFTEST.length - failed}/${SELFTEST.length} fixtures graded as expected`);
  return failed === 0;
}

function main(argv) {
  const args = argv.slice(2);
  const get = (flag) => {
    const i = args.indexOf(flag);
    return i >= 0 ? args[i + 1] : undefined;
  };
  if (args.includes('--selftest')) return selftest() ? 0 : 2;
  const range = get('--range');
  const eventPath = get('--event');
  if (!range && !eventPath) {
    console.error('usage: check-attribution.mjs --range <base>..<head> [--event <event.json>] | --selftest');
    return 2;
  }
  const all = [];
  let commits = [];
  if (range) {
    commits = commitsInRange(range);
    if (commits.length === 0 && !args.includes('--allow-empty')) {
      console.error(`attribution check: range ${range} yields no commits; refusing to report a pass on nothing.`);
      return 2;
    }
    all.push(...gradeCommits(commits));
  }
  all.push(...gradeEvent(eventPath));
  console.log(
    `attribution check: ${commits.length} commit(s) in ${range ?? '(no range)'}${eventPath ? ', plus PR title and body' : ''}`,
  );
  if (all.length === 0) {
    console.log('attribution check: clean.');
    return 0;
  }
  report(all);
  return 1;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.exit(main(process.argv));
}
