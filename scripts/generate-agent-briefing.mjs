// Generate docs/agent-briefing.md from the live briefing (run: pnpm gen:briefingdoc, which
// invokes this through tsx so the TS import below resolves).
//
// The text comes straight from `extensions/connector-core/src/briefing.ts`, the one module every
// connector renders its briefing from, so the page shows the words each harness hands its agent
// and cannot drift from them. `pnpm check:docsbundle` regenerates the page and fails on a diff.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { BRIEFING_HARNESSES, briefing } from "../extensions/connector-core/src/briefing.ts";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "docs", "agent-briefing.md");

// A representative agent: named, with a role, without a feedback key, so the page shows the
// keyless feedback sentence an agent on a plain mesh reads.
const config = { name: "alice", role: "reviewer", space: "main" };

/** Where each harness places the text, for the heading under each rendering. */
const PLACEMENT = {
  "claude-code": "Claude Code, launched by Cotal: the Cotal MCP server's instructions, so it sits in the system prompt. The session-start hook also hands over the orientation card at startup, resume, fork, clear and compaction.",
  codex: "Codex: `developerInstructions` on `thread/start`, added to Codex's own instructions.",
  jcode: "Jcode: the seat's instructions, as the first turn after any forked history.",
  opencode: "OpenCode: the system prompt of the first turn, after the persona. A seat with no persona gets none, because OpenCode's system prompt can only be replaced, never extended.",
  hermes: "Hermes: `SOUL.md` in the managed profile, after the persona. A seat with no persona gets none, for the same reason.",
  pi: "pi: appended to the system prompt while the send tools are active.",
  gateway: "A conversation that joined with `cotal_connect` (the Claude Code plugin in a session you opened, Claude Desktop, or a hosted connector): the connect result, after the orientation card. How messages arrive is said by the connect result's own listening line, so the briefing leaves that sentence out.",
};

const sections = BRIEFING_HARNESSES.map(
  (harness) => `## ${harness}\n\n${PLACEMENT[harness]}\n\n\`\`\`text\n${briefing(config, harness)}\n\`\`\`\n`,
);

const page = `# Agent briefing

> **Reference** · **For:** anyone reviewing what an agent is told when it joins · **Prereqs:** none

<!-- GENERATED by scripts/generate-agent-briefing.mjs from extensions/connector-core/src/briefing.ts. Do not edit by hand. -->

Every connector hands its agent one briefing when the session starts: who it is, to orient
first, when to send feedback, to keep multi-agent work on the mesh, when a durable workflow run
is the right tool, where to talk, how a peer message reaches it, how to reply, and the reply
etiquette. The paragraphs are written once, in the connector core, and each harness adds only
the sentence that says how a peer message appears in its model's context. This page is rendered
from that module for an agent named \`alice\` with the role \`reviewer\` in the space \`main\`,
so a wording change shows up here as a diff of what each harness will read.

The briefing is the ambient text. The live facts (identity, access, who is present, unread
count) are the orientation card, which \`cotal_orientation\` returns at any time and which the
connect result and the Claude Code session-start hook hand over without being asked.

${sections.join("\n")}`;

writeFileSync(out, page);
console.log(`gen:briefingdoc: wrote ${BRIEFING_HARNESSES.length} harness renderings → docs/agent-briefing.md`);
