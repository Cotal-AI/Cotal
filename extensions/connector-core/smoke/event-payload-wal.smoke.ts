import assert from "node:assert/strict";
import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { EventWal } from "../src/event-wal.js";
import { memorySubjectFrontier } from "@cotal-ai/smoke-kit";
const root = await mkdtemp(join(tmpdir(), "payload-wal-"));
const path = join(root, "wal.json");
const tuple = { space: "payload", threadId: "native", principal: "local.seat", subjectMayExist: false };
const wal = await EventWal.open(path, tuple);
await wal.bindSubjectFrontier(memorySubjectFrontier());
await wal.beginSend({ id: "publicframe", E: 0, seq: 1, sourceCursor: "cursor", body: [{kind:"text",text:"status"}], brackets: {run:undefined,text:[],reasoning:[],tools:[]}, payload: {id:"payloadframe", E:0, body:[{kind:"text",text:"payload"}]} });
await assert.rejects(wal.recordAck(2), /before sibling payload/);
await wal.recordPayloadAck(1);
const reopened = await EventWal.open(path, tuple);
await reopened.bindSubjectFrontier(memorySubjectFrontier());
assert.equal(reopened.pending?.payload?.ackSeq, 1);
assert.equal(reopened.pending?.payload?.id, "payloadframe");
await reopened.recordAck(2);
await reopened.fold();
assert.equal(reopened.frontier.sourceCursor,"cursor");
assert.equal(reopened.pending,null);
console.log("PASS frozen sibling payload survives restart and gates public cursor commit");
