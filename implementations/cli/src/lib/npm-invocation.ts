import { spawnSync } from "node:child_process";
import { lstatSync, realpathSync } from "node:fs";
import { homedir } from "node:os";
import { basename, delimiter, dirname, isAbsolute, join, parse, resolve } from "node:path";
import { decodeLocalJson, logicalExecutionEntry, protectedLocalDirectory, protectedLocalEntry, readLocalRecordSource, resolveOnPath } from "@cotal-ai/workspace";
import { Range } from "semver";

function npmPackage(file: string): { cli: string; node: Range } | undefined {
  const cli = realpathSync(file);
  const bin = dirname(cli);
  // Opaque shims may select their own npm. Only inspect the package of the actual npm CLI.
  if (basename(cli) !== "npm-cli.js" || basename(bin) !== "bin") return undefined;
  const path = join(dirname(bin), "package.json");
  // npm resolves linked manifests. Open the physical file with the same bounded record reader.
  const physical = lstatSync(path, { throwIfNoEntry: false })?.isSymbolicLink() ? realpathSync(path) : path;
  const manifest = readLocalRecordSource(physical);
  if (!manifest) return undefined;
  const meta = decodeLocalJson(manifest) as { name?: unknown; engines?: { node?: unknown } } | null;
  if (meta?.name !== "npm" || meta.engines?.node === undefined) return undefined;
  if (typeof meta.engines.node !== "string") throw new Error("npm's package declares an invalid Node.js engine range");
  try { return { cli, node: new Range(meta.engines.node, { includePrerelease: true }) }; }
  catch { throw new Error("npm's package declares an invalid Node.js engine range"); }
}

function recordedNode(): string | undefined {
  const entry = logicalExecutionEntry();
  if (!entry) return undefined;
  const root = dirname(dirname(entry));
  const modules = dirname(root);
  if (basename(modules) !== "node_modules" || basename(dirname(modules)) !== "lib") return undefined;
  const link = join(dirname(dirname(modules)), "bin", "cotal");
  const launcher = join(dirname(entry), "cotal-npm");
  const info = lstatSync(launcher, { throwIfNoEntry: false });
  if (!info?.isFile() || (info.uid !== process.getuid?.() && info.uid !== 0) || (info.mode & 0o022) !== 0) return undefined;
  if (!lstatSync(link, { throwIfNoEntry: false })?.isSymbolicLink()) return undefined;
  try { if (realpathSync(link) !== launcher) return undefined; }
  catch (error) { if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined; throw error; }
  protectedLocalDirectory(dirname(link), "the installed npm launcher directory");
  protectedLocalEntry(launcher, "the installed npm launcher");
  // Read the installation's pin, including launchers generated by an earlier release. Do not
  // execute the launcher or accept an inherited environment variable as the Node path.
  const source = readLocalRecordSource(launcher, 16_384)?.toString("utf8");
  const pin = source?.match(/^  node=('(?:[^'\n]|'\\'')*')$/m);
  const node = pin?.[1]?.slice(1, -1).replaceAll("'\\''", "'");
  return node && isAbsolute(node) ? node : undefined;
}

function compatibleNode(range: Range, env: NodeJS.ProcessEnv, cwd: string): string | undefined {
  const node = recordedNode();
  if (node && resolveOnPath(node)) {
    protectedLocalEntry(node, "the recorded Node executable");
    const { status, stdout } = spawnSync(node, ["--version"], { cwd, env, encoding: "utf8", timeout: 1000, killSignal: "SIGKILL", maxBuffer: 4096 });
    if (status === 0 && range.test(stdout.trim())) return node;
  }
  return undefined;
}

interface NpmInvocation {
  file: string;
  args: string[];
  env: NodeJS.ProcessEnv;
  cwd: string;
  unsupportedNode?: string;
}

export function npmInvocation(env: NodeJS.ProcessEnv, args: string[], { pinCurrent = true } = {}): NpmInvocation {
  const cwd = parse(homedir()).root;
  const original = { file: "npm", args, env, cwd };
  if (process.platform === "win32" || env.PATH === undefined) return original;
  const lookup = { PATH: env.PATH.split(delimiter).map(dir => resolve(cwd, dir)).join(delimiter) };
  const file = resolveOnPath("npm", lookup);
  if (!file) return original;
  const npm = npmPackage(file);
  if (!npm) return pinCurrent ? { ...original, file, env: withNodeOnPath(process.execPath, env, lookup) } : original;
  const outsideRange = !npm.node.test(process.version);
  const recorded = outsideRange ? compatibleNode(npm.node, env, cwd) : undefined;
  if (!recorded && !pinCurrent) return original;
  const node = recorded ?? process.execPath;
  // npm's engine declaration is advisory. Let the current Node run npm and report its own result.
  return {
    file: node, args: [npm.cli, ...args], env: withNodeOnPath(node, env, lookup), cwd,
    ...(outsideRange && !recorded ? { unsupportedNode: npm.node.raw } : {}),
  };
}

function withNodeOnPath(node: string, env: NodeJS.ProcessEnv, lookup: NodeJS.ProcessEnv): NodeJS.ProcessEnv {
  const bin = dirname(node);
  const alias = basename(node) === "node" ? node : resolveOnPath(join(bin, "node"));
  const pathNode = resolveOnPath("node", lookup);
  // Keep the existing PATH unless adding this directory would actually select the chosen Node.
  if (bin.includes(delimiter) || !alias || realpathSync(alias) !== realpathSync(node) ||
      pathNode && realpathSync(pathNode) === realpathSync(node)) return env;
  return { ...env, PATH: `${bin}${delimiter}${env.PATH}` };
}
