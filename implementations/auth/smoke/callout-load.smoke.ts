async function runChild(): Promise<void> {
  const chunks: Buffer[] = [];
  for await (const c of process.stdin) chunks.push(c as Buffer);
  const job = JSON.parse(Buffer.concat(chunks).toString("utf8")) as ChildJob;
  const cpu0 = process.cpuUsage();
  const attempts: Attempt[] = [];
  const held: NatsConnection[] = [];

  /** One connect through the real callout: sentinel creds + bearer, a per-connection inbox nonce
   *  as both `name` and `inboxPrefix` (the user-mode contract the callout scopes the reply inbox
   *  on). `keep` decides whether this models connect churn or a resident endpoint. */
  const once = async (bearer: string, keep: boolean): Promise<void> => {
    const nonce = `ibx${randomUUID().replace(/-/g, "")}`;
    const t0 = performance.now();
    try {
      const nc = await connect({
        servers: job.servers,
        authenticator: [credsAuthenticator(enc(job.sentinelCreds)), tokenAuthenticator(bearer)],
        name: nonce, inboxPrefix: `_INBOX_${nonce}`,
        timeout: job.connectTimeoutMs, maxReconnectAttempts: 0,
      });
      attempts.push({ ok: true, ms: performance.now() - t0 });
      if (keep) held.push(nc);
      else await nc.close();
    } catch (e) {
      attempts.push({ ok: false, ms: performance.now() - t0, reason: reasonOf(e) });
    }
  };

  const inflight = new Set<Promise<void>>();
  const fire = (bearer: string, keep: boolean) => {
    const p = once(bearer, keep).finally(() => inflight.delete(p));
    inflight.add(p);
  };

  let msgs = 0;
  const msgLatencies: number[] = [];
  const phase0 = performance.now();

  if (job.mode === "churn") {
    // Offer connects on a fixed schedule and never let a slow callout slow the OFFERED rate:
    // the harness must be able to overload the service, which is the measurement.
    const total = Math.round(job.ratePerSec! * job.seconds!);
    const startedAt = performance.now();
    let issued = 0;
    while (issued < total) {
      const due = Math.min(total, Math.floor(((performance.now() - startedAt) / 1000) * job.ratePerSec!) + 1);
      while (issued < due) fire(job.bearers[issued++ % job.bearers.length], false);
      await wait(2);
    }
  } else if (job.mode === "seats") {
    // Each seat reconnects on its own `pollMs` timer, phase-spread so N seats do not beat in
    // lockstep. This is the connect cadence of the connector's turn poll, nothing else.
    const until = performance.now() + job.seconds! * 1000;
    const seatLoops: Promise<void>[] = [];
    for (let s = 0; s < job.seats!; s++) {
      seatLoops.push((async () => {
        await wait((job.pollMs! / job.seats!) * s);
        while (performance.now() < until) {
          await once(job.bearers[s % job.bearers.length], false);
          await wait(job.pollMs!);
        }
      })());
    }
    await Promise.all(seatLoops);
  } else {
    // hold: bring up resident endpoints, then measure request/reply throughput between them.
    for (let i = 0; i < job.endpoints!; i++) await once(job.bearers[i % job.bearers.length], true);
    const live = held.filter(Boolean);
    if (live.length) {
      // Half the residents answer, half ask: a round-trip is one publish plus one reply, which is
      // what "messages per second per space" has to count.
      const half = Math.max(1, Math.floor(live.length / 2));
      for (let i = 0; i < half; i++) {
        const nc = live[i];
        void (async () => { for await (const m of nc.subscribe(job.subject!, { queue: "load" })) m.respond(m.data); })().catch(() => {});
      }
      await Promise.all(live.slice(0, half).map((nc) => nc.flush()));
      const askers = live.slice(half);
      const until = performance.now() + job.seconds! * 1000;
      const payload = enc("x".repeat(128));
      await Promise.all(askers.map(async (nc) => {
        const lanes = Array.from({ length: job.inflight ?? 4 }, async () => {
          while (performance.now() < until) {
            const t0 = performance.now();
            try { await nc.request(job.subject!, payload, { timeout: 5000 }); msgs++; msgLatencies.push(performance.now() - t0); }
            catch { /* a dropped round-trip is simply not counted */ }
          }
        });
        await Promise.all(lanes);
      }));
    }
  }

  const loadMs = performance.now() - phase0;
  // Let every offered connect settle so "attempted" and "succeeded" describe the same set.
  const drainUntil = performance.now() + job.connectTimeoutMs + 5000;
  while (inflight.size && performance.now() < drainUntil) await Promise.race([Promise.allSettled([...inflight]), wait(250)]);
  for (const nc of held) { try { await nc.close(); } catch { /* closing a dead conn is not a result */ } }

  const cpu = process.cpuUsage(cpu0);
  const byReason: Record<string, number> = {};
  for (const a of attempts) if (!a.ok) byReason[a.reason!] = (byReason[a.reason!] ?? 0) + 1;
  const out: ChildResult = {
    attempts: attempts.length,
    ok: attempts.filter((a) => a.ok).length,
    byReason,
    latencies: attempts.filter((a) => a.ok).map((a) => a.ms),
    msgs, msgLatencies,
    cpuMs: (cpu.user + cpu.system) / 1000,
    loadMs,
  };
  process.stdout.write(RESULT_PREFIX + JSON.stringify(out) + "\n");
}

if (process.argv[2] === "load") { await runChild(); process.exit(0); }

