/** One connect attempt as a load child saw it. `ms` is the client-side connect wall time. */
interface Attempt { ok: boolean; ms: number; reason?: string }
/** What a load child reports back on stdout when its phase is over. */
interface ChildResult {
  attempts: number;
  ok: number;
  byReason: Record<string, number>;
  latencies: number[];
  /** Request/reply round-trips completed by a `hold` child, and their latencies. */
  /** hold: messages published into the space. */
  msgs?: number;
  /** hold: message deliveries the broker actually made (fan-out, so >= msgs). */
  received?: number;
  msgLatencies?: number[];
  cpuMs: number;
  /** The pacing window alone. Offered rate must not be divided by the drain that follows it. */
  loadMs: number;
}
/** The job one load child runs. Carries credential material, so it travels over stdin only. */
interface ChildJob {
  mode: "churn" | "seats" | "hold";
  servers: string;
  sentinelCreds: string;
  bearers: string[];
  connectTimeoutMs: number;
  /** churn: offered connects per second, for `seconds`. */
  ratePerSec?: number;
  seconds?: number;
  /** seats: how many seats this child animates, each reconnecting every `pollMs`. */
  seats?: number;
  pollMs?: number;
  /** hold: how many connections stay resident, then drive request/reply for `seconds`. */
  endpoints?: number;
  /** hold: the channel-wildcard subject every resident subscribes (`chat.*.*.<channel>`). */
  subSubject?: string;
  /** hold: per-bearer publish subjects (`chat.<owner>.<actor>.<channel>`), aligned with `bearers`. */
  pubSubjects?: string[];
}

// Scrub any ambient COTAL_* before anything is handed to a child. Whatever runs this harness may
// itself be a managed agent session, and its COTAL_SERVERS / credential variables name a LIVE mesh:
// a bare `...process.env` would hand a load child a real broker and a real identity, which is a
// different mesh from the private one this harness builds and measures. Enforced tree-wide by
// `smoke:suite-ambient-env`.
const cleanEnv: NodeJS.ProcessEnv = { ...process.env };
for (const k of Object.keys(cleanEnv)) if (k.startsWith("COTAL_")) delete cleanEnv[k];

const RESULT_PREFIX = "RESULT ";
/** Keep every Nth delivery latency, and never more than this many, so one run's result stays a
 *  document the parent can parse. Percentiles over a systematic sample of a steady stream are
 *  the same percentiles. */
const DELIVERY_SAMPLE = 64;
const MAX_LATENCY_SAMPLES = 50_000;
const enc = (s: string) => new TextEncoder().encode(s);
const wait = (ms: number) => new Promise((r) => setTimeout(r, ms));

/** Nearest-rank percentile over an unsorted sample array. 0 samples reports NaN, never a 0 that
 *  would read as a fast run. */
function pct(xs: number[], p: number): number {
  if (!xs.length) return NaN;
  const s = [...xs].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.max(0, Math.ceil((p / 100) * s.length) - 1))];
}

/** Fold a client connect failure into a stable bucket. NATS reports a callout denial as the
 *  generic "Authorization Violation" (the callout's reason stays server-side), and a callout that
 *  never answered as a client-side connect timeout; keeping those apart is the whole point. */
function reasonOf(e: unknown): string {
  const m = (e instanceof Error ? e.message : String(e)).toLowerCase();
  if (m.includes("authorization violation")) return "Authorization Violation";
  if (m.includes("authentication timeout")) return "authentication timeout (broker)";
  if (m.includes("timeout")) return "connect timeout (client)";
  if (m.includes("econnrefused")) return "ECONNREFUSED";
  if (m.includes("econnreset")) return "ECONNRESET";
  if (m.includes("emfile") || m.includes("enfile")) return "fd exhaustion";
  if (m.includes("maximum connections") || m.includes("too many")) return "broker conn limit";
  if (m.includes("stale connection")) return "stale connection";
  return (e instanceof Error ? e.message : String(e)).slice(0, 60);
}

