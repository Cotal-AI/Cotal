/**
 * Auth-callout CONNECT-LOAD harness — capacity, not correctness.
 *
 * Boots a private operator-mode nats-server with the real callout account, runs the REAL
 * `startAuthCallout` service, mints valid user bearers, and drives connects with the real NATS
 * client through the real callout path. It reports connects attempted / succeeded / refused by
 * reason, callout handler latency percentiles, client-side connect latency percentiles, and the
 * CPU and RSS of the broker and the auth service, so the first saturating resource is read off
 * the run rather than guessed.
 *
 * TWO ARMS, so a gain is measured rather than claimed:
 *  - `--arm main`  — this worktree's `../src/callout.js` (native Ed25519 signer, `maxInFlight 32`);
 *  - `--arm stock` — the callout as shipped in **v0.99.3** (pure-JS signer, one request at a time),
 *    extracted with `git show v0.99.3:implementations/auth/src/callout.ts`. It is the real
 *    historical file, not a reconstruction: the run pins its sha256 and refuses to continue if the
 *    blob is not the expected one. Both arms run against the SAME current siblings (`./token.js`,
 *    `./permissions.js`, …), which isolates the two callout deltas under test; everything else in
 *    the process is identical. Following the house pattern of
 *    `extensions/connector-core/smoke/egress-guard-differential.smoke.ts`, the historical copy is
 *    written next to the live `src/` (so its `./token.js` imports resolve), named with a leading
 *    dot, gitignored, and removed in `finally`.
 *
 * Load is generated by CHILD PROCESSES (at most `--load-procs`, default 4), never in this process:
 * the auth service runs here, and a load generator sharing this event loop would be billed to the
 * auth service's own CPU and make the bottleneck unreadable. Credentials reach a child over stdin,
 * never argv.
 *
 * Run (needs a nats-server on PATH, or NATS_SERVER_BIN):
 *   pnpm smoke:callout-load --scenario steady --arm main --rate 200 --seconds 20
 */
