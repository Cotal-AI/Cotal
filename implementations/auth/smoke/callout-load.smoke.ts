  if (got !== STOCK_SHA256) throw new Error(`callout-load: ${STOCK_REF}:${CALLOUT_PATH} is ${got}, expected ${STOCK_SHA256} - refusing to measure an unpinned control`);
  const retargeted = blob.replace(/from "\.\//g, 'from "../src/');
  const rewrote = (blob.match(/from "\.\//g) ?? []).length;
  if (rewrote !== 4) throw new Error(`callout-load: expected 4 relative sibling imports in the ${STOCK_REF} callout, retargeted ${rewrote}`);
  const dest = join(SRC_DIR, `.callout-load-arm-${process.pid}-${STOCK_REF}.ts`);
  writeFileSync(dest, retargeted);
  armFiles.push(dest);
