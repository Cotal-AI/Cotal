/**
 * One callout process serving several spaces, on a real user-auth broker.
 *
 * The host (`cotal auth-service --callout-only --spaces <manifest>`) runs as its own daemon process
 * holding one callout lane per space. Every space is a real provisioned user-auth space with its own
 * auth account, its own data account and its own signing keys, all under one broker operator, as a
 * hosted deployment leaves them.
 *
 * Cells: one process answers connects for two spaces; a space's callout requests reach only its own
 * lane's subscription, read from the broker's own per-subscription counters; a connection minted by
 * one lane is bound into that space's data account and never the other's, read from the broker's
 * own `/connz`; a bearer for one space is refused by the other space's lane; a lane removed from the
 * manifest closes while the other keeps answering every connect; a lane added to the manifest starts
 * answering; a manifest that does not read or parse whole keeps the live lanes; at startup the host
 * answers for the spaces it can and names and retries the rest: a never-provisioned space, and a space
 * whose admission a run with `--service-endpoints` opened, which never gets a lane in this process
 * while the other spaces' connects are answered by it alone; `admitsServiceEndpoints` answers the
 * same set the host refused; a single-space replica still refuses that space at startup.
 *
 * `--measure` instead reports RSS and CPU per space for 1, 4 and 16 lanes in one process against 16
 * single-space replica processes, under the same offered connect rate. Load is generated by the
 * callout-load harness's `load` child, never in this process.
 *
 * The refused space is also retried for `--soak` seconds (default 180) while the host runs, and the
 * host's open descriptors, RSS and broker connections are sampled: retrying it must not grow them.
 *
 * Run: pnpm smoke:callout-multi-tenant [--rate 20] [--seconds 6] [--soak 180]   (nats-server on PATH, or NATS_SERVER_BIN)
 *      pnpm smoke:callout-multi-tenant --measure [--rate 16] [--seconds 20]
 */
import assert from "node:assert/strict";
import { SMOKE_BROKER_TOKEN, killAndAwaitExit, teardownOnSignal } from "@cotal-ai/smoke-kit";

if (process.argv[2] === "__daemon-auth-service") {
  await import("@cotal-ai/auth");
  const { parseCommandArgs, registry } = await import("@cotal-ai/core");
  type Command = import("@cotal-ai/core").Command;
  const command = registry.all<Command>("command").find((c) => c.name === process.argv[2])!;
  await command.run(parseCommandArgs(command, process.argv.slice(3)));
} else {
  const { spawn } = await import("node:child_process");
  const { mkdirSync, mkdtempSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } = await import("node:fs");
  const { createServer } = await import("node:http");
  const { tmpdir } = await import("node:os");
  const { join } = await import("node:path");
  const { randomUUID } = await import("node:crypto");
  type ChildProcess = import("node:child_process").ChildProcess;

  const home = mkdtempSync(join(tmpdir(), `${SMOKE_BROKER_TOKEN}callout-mt-`));
  const root = join(home, "workspace");
  mkdirSync(root);
  for (const key of Object.keys(process.env)) if (key.startsWith("COTAL_") && key !== "COTAL_TELEMETRY") delete process.env[key];
  process.env.COTAL_HOME = home;

  const { connect, credsAuthenticator, tokenAuthenticator } = await import("@nats-io/transport-node");
  const { createBrokerAuth, createSpaceAccountAuth, isReachable, mintCreds, mintLifecycleUid, newIdentity, serverConfig, setupSpaceStreams } = await import("@cotal-ai/core");
  const { authDir, saveSpaceAuth, userAuthStateDir, workspaceSecretStore } = await import("@cotal-ai/workspace");
  const { admitsServiceEndpoints, cotalAuthProvider, grantManagedActor, loadAuthServiceInfo, loadCalloutAuth, newActorToken, parseSpaceManifest } = await import("@cotal-ai/auth");
  const { saveIdpSession } = await import("../src/login.js");
  const { pickFreePort } = await import("./_free-port.js");

  const argv = process.argv.slice(2);
  const MEASURE = argv.includes("--measure");
  const num = (name: string, dflt: number): number => {
    const i = argv.indexOf(`--${name}`);
    const v = i >= 0 ? Number(argv[i + 1]) : dflt;
    if (!Number.isFinite(v) || v <= 0) throw new Error(`callout-multi-tenant: --${name} must be a positive number`);
    return v;
  };
  const RATE = num("rate", MEASURE ? 2 : 20), SECONDS = num("seconds", MEASURE ? 20 : 6), USERS = num("users", 4), SOAK = num("soak", 180);
  const NATS_BIN = process.env.NATS_SERVER_BIN ?? "nats-server";
  const MEASURE_LANES = [1, 4, 16];
  // Outside --measure the third space is E: its primary runs once with --service-endpoints, which
  // opens its service endpoint admission for good.
  const SPACE_COUNT = MEASURE ? Math.max(...MEASURE_LANES) : 3;

  const wait = (ms: number) => new Promise<void>((r) => setTimeout(r, ms));
  const until = async (test: () => boolean | Promise<boolean>, message: string, ms = 60_000) => {
    const end = Date.now() + ms;
    while (Date.now() < end) { if (await test()) return; await wait(100); }
    throw new Error(message);
  };
  let passed = 0;
  const check = (name: string, condition: unknown, detail?: unknown) => {
    assert(condition, `${name}${detail === undefined ? "" : ` ${JSON.stringify(detail)}`}`);
    passed++;
    console.log(`  ✓ ${name}${detail === undefined ? "" : ` ${JSON.stringify(detail)}`}`);
  };

  // ---- /proc readings -----------------------------------------------------------------------------
  /** Resident set size in MB. */
  const rssMb = (pid: number): number => {
    const m = /VmRSS:\s+(\d+) kB/.exec(readFileSync(`/proc/${pid}/status`, "utf8"));
    if (!m) throw new Error(`no VmRSS for pid ${pid}`);
    return Number(m[1]) / 1024;
  };
  /** utime + stime in ms (Linux, 100 ticks per second). */
  const cpuMs = (pid: number): number => {
    const f = readFileSync(`/proc/${pid}/stat`, "utf8").split(") ")[1].split(" ");
    return (Number(f[11]) + Number(f[12])) * 10;
  };

  const port = await pickFreePort();
  const monPort = await pickFreePort();
  const servers = `nats://127.0.0.1:${port}`;
  const store = workspaceSecretStore(root);
  const childEnv: NodeJS.ProcessEnv = { ...process.env };
  for (const key of Object.keys(childEnv)) if (key.startsWith("COTAL_")) delete childEnv[key];
  childEnv.COTAL_HOME = home;
  childEnv.COTAL_TELEMETRY = "off";
  childEnv.DO_NOT_TRACK = "1";

  const idp = createServer((_req, res) => { res.writeHead(200, { "content-type": "application/json" }); res.end('{"keys":[]}'); });
  await new Promise<void>((resolve) => idp.listen(0, "127.0.0.1", resolve));
  const idpUrl = `http://127.0.0.1:${(idp.address() as import("node:net").AddressInfo).port}/auth`;

  let broker: ChildProcess | undefined;
  let releaseBroker: (() => void) | undefined;
  const daemons = new Map<string, { child: ChildProcess; out: string[] }>();
  const loads = new Set<ChildProcess>();

  /** One provisioned space: what a lane loads and what a client needs to connect to it. */
  interface Space {
    name: string;
    /** The data account users are bound into. Two spaces never share one. */
    dataAccountPub: string;
    sentinelCreds: string;
    bearers: string[];
  }

  const exited = (child: ChildProcess) => new Promise<number | null>((resolve) => {
    if (child.exitCode !== null || child.signalCode !== null) return resolve(child.exitCode);
    child.once("exit", (code) => resolve(code));
  });

  /** Start one auth-service daemon process. `nodeArgs` go to node ahead of the script. */
  const startDaemon = (label: string, args: string[], nodeArgs: string[] = []) => {
    const child = spawn(process.execPath, [...process.execArgv, ...nodeArgs, import.meta.filename, "__daemon-auth-service", "--server", servers, ...args],
      { cwd: root, env: childEnv, stdio: ["ignore", "pipe", "pipe"] });
    const out: string[] = [];
    child.stdout!.setEncoding("utf8").on("data", (d: string) => out.push(d));
    child.stderr!.setEncoding("utf8").on("data", (d: string) => out.push(d));
    daemons.set(label, { child, out });
    return { child, out };
  };
  const stopDaemon = async (label: string) => {
    const d = daemons.get(label);
    if (!d || d.child.exitCode !== null) return;
    await killAndAwaitExit(d.child, "SIGTERM");
  };

  // ---- callouts per callout connection, from the broker's subscription counters -------------------
  interface Connz { connections: Array<{ cid: number; port: number; name?: string; account?: string; reason?: string; subscriptions_list_detail?: Array<{ subject: string; qgroup?: string; msgs: number }> }> }
  const connz = async (): Promise<Connz> =>
    await (await fetch(`http://127.0.0.1:${monPort}/connz?subs=detail&auth=1&limit=8192`)).json() as Connz;
  /** Every connection the broker has seen with this name, open or already closed. A connect the
   *  broker refused is listed too, closed, with no account. */
  const everNamed = async (name: string) =>
    ((await (await fetch(`http://127.0.0.1:${monPort}/connz?state=all&auth=1&limit=10000`)).json()) as Connz).connections.filter((c) => c.name === name);
  /** Members of `space`'s callout queue group, by connection name. */
  const calloutMembers = async (space: string): Promise<string[]> =>
    (await connz()).connections.filter((c) => c.name?.endsWith(`:${space}`) && (c.subscriptions_list_detail ?? []).some((s) => s.subject === "$SYS.REQ.USER.AUTH" && s.qgroup === "cotal-auth-callout")).map((c) => c.name!).sort();
  /** Callouts answered per lane, keyed by the connection name a lane gives its callout connection. */
  const calloutsByLane = async (): Promise<Record<string, number>> => {
    const counts: Record<string, number> = {};
    for (const c of (await connz()).connections) {
      if (!c.name?.startsWith("cotal:auth-callout-replica:")) continue;
      const space = c.name.slice("cotal:auth-callout-replica:".length);
      for (const s of c.subscriptions_list_detail ?? [])
        if (s.subject === "$SYS.REQ.USER.AUTH" && s.qgroup === "cotal-auth-callout") counts[space] = (counts[space] ?? 0) + s.msgs;
    }
    return counts;
  };
  const delta = (before: Record<string, number>, after: Record<string, number>) =>
    Object.fromEntries([...new Set([...Object.keys(before), ...Object.keys(after)])].map((k) => [k, (after[k] ?? 0) - (before[k] ?? 0)]));

  // ---- load, from the callout-load harness's own child --------------------------------------------
  interface LoadResult { attempts: number; ok: number; byReason: Record<string, number> }
  const harness = join(import.meta.dirname, "callout-load.smoke.ts");
  /** Drive `seconds` of connect churn at `ratePerSec` against one space. */
  const load = (space: Space, seconds: number, ratePerSec: number): Promise<LoadResult> =>
    new Promise((resolve, reject) => {
      const child = spawn(process.execPath, [...process.execArgv, harness, "load"], { stdio: ["pipe", "pipe", "inherit"], env: childEnv });
      loads.add(child);
      let out = "";
      child.stdout!.setEncoding("utf8").on("data", (d: string) => { out += d; });
      child.on("error", reject);
      child.on("close", (code) => {
        loads.delete(child);
        const line = out.split("\n").find((l) => l.startsWith("RESULT "));
        if (!line) return reject(new Error(`load child exited ${code} with no result`));
        resolve(JSON.parse(line.slice("RESULT ".length)) as LoadResult);
      });
      child.stdin!.end(JSON.stringify({ mode: "churn", servers, sentinelCreds: space.sentinelCreds, bearers: space.bearers, connectTimeoutMs: 10_000, ratePerSec, seconds }));
    });
  const loadAll = async (spaces: Space[], seconds: number, ratePerSec: number): Promise<LoadResult> => {
    const rs = await Promise.all(spaces.map((s) => load(s, seconds, ratePerSec)));
    return {
      attempts: rs.reduce((a, r) => a + r.attempts, 0),
      ok: rs.reduce((a, r) => a + r.ok, 0),
      byReason: rs.reduce<Record<string, number>>((a, r) => { for (const [k, v] of Object.entries(r.byReason)) a[k] = (a[k] ?? 0) + v; return a; }, {}),
    };
  };

  /** One connect through the real callout, as a client makes it. Resolves the broker's view of the
   *  connection it produced, which names the account the minted JWT bound it into. */
  const connectOnce = async (space: Space, bearer: string) => {
    const nonce = `ibx${randomUUID().replace(/-/g, "")}`;
    const nc = await connect({
      servers, authenticator: [credsAuthenticator(new TextEncoder().encode(space.sentinelCreds)), tokenAuthenticator(bearer)],
      name: nonce, inboxPrefix: `_INBOX_${nonce}`, timeout: 10_000, maxReconnectAttempts: 0,
    });
    const seen = (await connz()).connections.find((c) => c.name === nonce);
    await nc.close();
    if (!seen) throw new Error(`the broker reported no connection named ${nonce}`);
    return seen;
  };

  // ---- the manifest -------------------------------------------------------------------------------
  const manifestPath = join(home, "spaces.json");
  /** Replace the manifest the way a provisioning backend does: write a sibling and rename it into
   *  place, so a reader never sees a partial file. */
  const writeManifest = (names: string[]) => {
    const tmp = `${manifestPath}.${randomUUID().slice(0, 8)}`;
    writeFileSync(tmp, JSON.stringify({ version: 1, spaces: names }, null, 2));
    renameSync(tmp, manifestPath);
  };

  let complete = false;
  console.log(`callout-multi-tenant: ${SPACE_COUNT} space(s), ${RATE} connects/s per space, ${SECONDS}s per phase${MEASURE ? " [measure]" : ""}`);
  try {
    // ---- one broker operator, N provisioned user-auth spaces ------------------------------------
    const brokerAuth = await createBrokerAuth("callout-mt");
    const names = Array.from({ length: SPACE_COUNT }, (_, i) => `mt${i}-${process.pid}`);
    const accounts = await Promise.all(names.map((n) => createSpaceAccountAuth(brokerAuth, n)));
    const spaceAuths = accounts.map((a) => ({ ...brokerAuth, ...a }));
    const extraAccounts: Array<{ pub: string; jwt: string }> = [];
    for (const auth of spaceAuths) {
      saveSpaceAuth(authDir(root), auth);
      const prepared = await cotalAuthProvider.prepareServer({
        space: auth.space, operatorSeed: brokerAuth.operator.seed,
        account: { pub: auth.account.pub, signingSeed: auth.account.signingSeed },
        store, dir: userAuthStateDir(root, auth.space), idpUrl,
      });
      extraAccounts.push(...prepared.extraAccounts);
    }
    const conf = join(home, "server.conf");
    writeFileSync(conf, serverConfig(brokerAuth, accounts, { transport: { kind: "plaintext" }, port, storeDir: join(home, "js"), extraAccounts })
      + `\nhttp: 127.0.0.1:${monPort}\n`);
    broker = spawn(NATS_BIN, ["-c", conf], { stdio: "ignore" });
    releaseBroker = teardownOnSignal(broker, home);
    await until(async () => broker!.exitCode === null && await isReachable(servers), "the user-auth broker did not bind");
    saveIdpSession(home, idpUrl, { token: "mt-fixture-session", sub: "mt-fixture-human", expiresAt: Math.floor(Date.now() / 1000) + 3600 });

    // Each space gets its streams, its actor grants, and real bearers from its own primary's
    // exchange (the only writer of the credential ledger rows a connect is checked against). The
    // primary is stopped once its bearers exist: what is measured is the callout, not the primary.
    const spaces: Space[] = [];
    for (const auth of spaceAuths) {
      const space = auth.space;
      const stateDir = userAuthStateDir(root, space);
      await setupSpaceStreams({ space, servers, creds: await mintCreds(auth, newIdentity(), "provisioner") });
      const owner = await cotalAuthProvider.ownerForLogin({ store, dir: stateDir, space });
      const actors = Array.from({ length: USERS }, (_, i) => {
        const { actorToken, tokenHash } = newActorToken();
        grantManagedActor(stateDir, { custody: { kind: "foreground" }, owner, actor: `load_${i}`, scope: [], allowSubscribe: ["general"], allowPublish: ["general"], tokenHash, lifecycleUid: mintLifecycleUid() });
        return { actor: `load_${i}`, actorToken };
      });
      const label = `primary:${space}`;
      const primary = startDaemon(label, ["--space", space, ...(!MEASURE && spaces.length === 2 ? ["--service-endpoints"] : [])]);
      await until(() => loadAuthServiceInfo(stateDir)?.pid === primary.child.pid || primary.child.exitCode !== null,
        `the primary for ${space} did not write its auth-service.json: ${primary.out.join("")}`);
      if (primary.child.exitCode !== null) throw new Error(`the primary for ${space} exited ${primary.child.exitCode}: ${primary.out.join("")}`);
      const info = loadAuthServiceInfo(stateDir)!;
      const bearers = await Promise.all(actors.map(async ({ actor, actorToken }) => {
        const res = await fetch(`${info.url}/exchange`, { method: "POST", headers: { "content-type": "application/json", authorization: `Bearer ${info.cap}` }, body: JSON.stringify({ owner, actor, actorToken }) });
        const body = await res.json() as { token?: string; error?: string };
        if (!res.ok || !body.token) throw new Error(`exchange for ${actor} in ${space} refused: ${body.error ?? res.status}`);
        return body.token;
      }));
      await stopDaemon(label);
      spaces.push({ name: space, dataAccountPub: auth.account.pub, sentinelCreds: (await loadCalloutAuth(store, space))!.sentinelCreds, bearers });
    }
    console.log(`  provisioned ${spaces.length} space(s)`);

    if (MEASURE) {
      // ---- the measured table ---------------------------------------------------------------------
      /** Settle the process's own allocations before reading RSS, so the figure is the lanes and not
       *  the transient of their startup. */
      const settle = async () => { await wait(3000); };
      interface Row { shape: string; procs: number; lanes: number; rssMb: number; cpuCores: number; ok: number; attempts: number; loadavg: number }
      const table: Row[] = [];

      const measure = async (shape: string, labels: string[], served: Space[]): Promise<void> => {
        await settle();
        const pids = labels.map((l) => daemons.get(l)!.child.pid!);
        const cpu0 = pids.reduce((a, p) => a + cpuMs(p), 0);
        const t0 = performance.now();
        const result = await loadAll(served, SECONDS, RATE);
        const elapsed = (performance.now() - t0) / 1000;
        await settle();
        const rss = pids.reduce((a, p) => a + rssMb(p), 0);
        const cpu = (pids.reduce((a, p) => a + cpuMs(p), 0) - cpu0) / 1000 / elapsed;
        const loadavg = Number(readFileSync("/proc/loadavg", "utf8").split(" ")[0]);
        table.push({ shape, procs: labels.length, lanes: served.length, rssMb: Number(rss.toFixed(1)), cpuCores: Number(cpu.toFixed(2)), ok: result.ok, attempts: result.attempts, loadavg });
        console.log(`  measured ${JSON.stringify(table.at(-1))}`);
      };

      for (const lanes of MEASURE_LANES) {
        const served = spaces.slice(0, lanes);
        writeManifest(served.map((s) => s.name));
        const label = `host:${lanes}`;
        const host = startDaemon(label, ["--callout-only", "--spaces", manifestPath]);
        await until(() => host.out.join("").includes("✓ auth callout host up") || host.child.exitCode !== null, `the ${lanes}-lane host did not come up: ${host.out.join("")}`);
        if (host.child.exitCode !== null) throw new Error(`the ${lanes}-lane host exited ${host.child.exitCode}: ${host.out.join("")}`);
        await measure(`${lanes} lane(s), one process`, [label], served);
        await stopDaemon(label);
      }

      const procLabels: string[] = [];
      for (const s of spaces) {
        const label = `replica:${s.name}`;
        const r = startDaemon(label, ["--callout-only", "--space", s.name]);
        await until(() => r.out.join("").includes("✓ auth callout replica up") || r.child.exitCode !== null, `the replica for ${s.name} did not come up: ${r.out.join("")}`);
        if (r.child.exitCode !== null) throw new Error(`the replica for ${s.name} exited ${r.child.exitCode}: ${r.out.join("")}`);
        procLabels.push(label);
      }
      await measure(`${spaces.length} single-space processes`, procLabels, spaces);
      for (const label of procLabels) await stopDaemon(label);

      console.log("");
      console.log("| shape | processes | spaces | RSS total (MB) | RSS per space (MB) | CPU (cores) | CPU per space | connects ok | host loadavg |");
      console.log("| --- | --- | --- | --- | --- | --- | --- | --- | --- |");
      for (const r of table)
        console.log(`| ${r.shape} | ${r.procs} | ${r.lanes} | ${r.rssMb} | ${(r.rssMb / r.lanes).toFixed(1)} | ${r.cpuCores} | ${(r.cpuCores / r.lanes).toFixed(3)} | ${r.ok}/${r.attempts} | ${r.loadavg} |`);
      console.log("");
      const one16 = table.find((r) => r.shape.startsWith("16 lane"))!;
      const many16 = table.find((r) => r.shape.includes("single-space processes"))!;
      check("16 lanes in one process hold less RSS than 16 single-space processes", one16.rssMb < many16.rssMb, { oneProcess: one16.rssMb, sixteenProcesses: many16.rssMb });
      check("both shapes answered the same offered load", one16.attempts === many16.attempts, { one: one16.attempts, many: many16.attempts });
      if (one16.ok !== one16.attempts || many16.ok !== many16.attempts)
        console.log(`  note: connects were lost under load (one process ${one16.ok}/${one16.attempts}, ${many16.procs} processes ${many16.ok}/${many16.attempts}); this host's loadavg was ${one16.loadavg} and ${many16.loadavg}`);
      complete = true;
    } else {
      // ---- startup refusals -----------------------------------------------------------------------
      writeManifest([spaces[0].name, spaces[1].name]);
      for (const [why, args, expect] of [
        ["--spaces without --callout-only (the full host) on a version 1 manifest", ["--spaces", manifestPath], "version must be 2"],
        ["--space with --spaces", ["--callout-only", "--space", spaces[0].name, "--spaces", manifestPath], "are alternatives"],
      ] as Array<[string, string[], string]>) {
        const refused = startDaemon(`refused:${why}`, args);
        const code = await exited(refused.child);
        check(`${why} refuses`, code !== 0 && refused.out.join("").includes(expect), refused.out.join("").trim().slice(0, 140));
      }
      const unprovisioned = join(home, "unprovisioned.json");
      writeFileSync(unprovisioned, JSON.stringify({ version: 1, spaces: [spaces[0].name, "never-provisioned"] }));
      const servable = startDaemon("servable:unprovisioned", ["--callout-only", "--spaces", unprovisioned]);
      await until(() => servable.out.join("").includes("✓ auth callout host up") || servable.child.exitCode !== null, `the host did not come up: ${servable.out.join("")}`);
      check("a manifest naming a never-provisioned space starts the host, answering for the other space and retrying the missing one",
        servable.child.exitCode === null && servable.out.join("").includes(`(1 of 2 space(s) answering: ${spaces[0].name}; retrying never-provisioned)`)
          && servable.out.join("").includes('space "never-provisioned" could not be served'),
        servable.out.join("").trim().slice(0, 300));
      await stopDaemon("servable:unprovisioned");

      // ---- a space whose service endpoint admission is open -------------------------------------------
      // E's primary ran with --service-endpoints during provisioning and is stopped, as A's and B's
      // are, so this host is the only callout member A and B have, and nothing answers E.
      const E = spaces[2];
      writeManifest([spaces[0].name, spaces[1].name, E.name]);
      // The soak below reads this host's RSS. V8 grows its young generation to as much as 128 MB and
      // maps and releases those pages, and the buffers that die there, on its own schedule, which
      // moved RSS by up to 60 MB with nothing retained. An object a retry keeps survives into the old
      // generation, which RSS still counts, so a fixed 1 MB semi-space removes V8's sizing from the
      // reading and still measures what the retries keep.
      const mixed = startDaemon("mixed", ["--callout-only", "--spaces", manifestPath], ["--max-semi-space-size=1"]);
      await until(() => mixed.out.join("").includes("✓ auth callout host up") || mixed.child.exitCode !== null, `the mixed host did not come up: ${mixed.out.join("")}`);
      const retries = () => mixed.out.join("").split("\n").filter((l) => l.includes(`space "${E.name}" could not be served`) && l.includes("admits service endpoints")).length;
      check("a host naming a space with open service endpoint admission starts and answers for every other space",
        mixed.child.exitCode === null && mixed.out.join("").includes(`(2 of 3 space(s) answering: ${spaces[0].name}, ${spaces[1].name}; retrying ${E.name})`),
        mixed.out.join("").trim().slice(0, 300));
      await until(() => retries() >= 2, `the host did not retry ${E.name} twice: ${mixed.out.join("").slice(-400)}`, 30_000);
      check("the refused space is named with its admission and retried", retries() >= 2, retries());
      const members = Object.fromEntries(await Promise.all(spaces.map(async (s) => [s.name, await calloutMembers(s.name)])));
      check("the broker counts a callout member from this host for each plain space and none for the refused space",
        members[spaces[0].name].length === 1 && members[spaces[1].name].length === 1 && members[E.name].length === 0, members);
      const plain = await loadAll(spaces.slice(0, 2), 2, 4);
      check("every connect to the plain spaces is answered by this host alone", plain.ok === plain.attempts && plain.ok > 0, { ok: plain.ok, attempts: plain.attempts, byReason: plain.byReason });
      // Each attempt names its connection, so the broker's record of every connection it ever admitted
      // says whether any was authorized. The host's callout writes one journal line per request it
      // answers, so its lines say whether it answered any for E; A's and B's lines are the control.
      const eAttempts = 3;
      const eRefusals: string[] = [];
      let eAuthorized = 0;
      const eSeen: Array<{ account: string | null; reason: string | null }> = [];
      for (let i = 0; i < eAttempts; i++) {
        const nonce = `ibx${randomUUID().replace(/-/g, "")}`;
        try {
          const nc = await connect({ servers, authenticator: [credsAuthenticator(new TextEncoder().encode(E.sentinelCreds)), tokenAuthenticator(E.bearers[0])],
            name: nonce, inboxPrefix: `_INBOX_${nonce}`, timeout: 10_000, maxReconnectAttempts: 0 });
          await nc.close();
        } catch (e) { eRefusals.push(e instanceof Error ? e.message : String(e)); }
        const seen = await everNamed(nonce);
        eSeen.push(...seen.map((c) => ({ account: c.account ?? null, reason: c.reason ?? null })));
        eAuthorized += seen.filter((c) => c.account === E.dataAccountPub).length;
      }
      const journalFor = (space: string) => mixed.out.join("").split("\n").filter((l) => l.startsWith("auth callout:") && l.includes(` space=${space} `)).length;
      check("every connect to the refused space is refused and none is authorized",
        eRefusals.length === eAttempts && eSeen.length >= eAttempts && eAuthorized === 0 && eSeen.every((c) => c.account !== E.dataAccountPub),
        { attempts: eAttempts, refused: eRefusals.length, authorized: eAuthorized, broker: eSeen, sample: eRefusals[0]?.slice(0, 60) });
      check("this host answered no callout for the refused space and answered the plain spaces' callouts",
        journalFor(E.name) === 0 && journalFor(spaces[0].name) > 0 && journalFor(spaces[1].name) > 0,
        { [E.name]: journalFor(E.name), [spaces[0].name]: journalFor(spaces[0].name), [spaces[1].name]: journalFor(spaces[1].name) });
      // Across every retry the lane opened its store connection, read the admission and closed it: the
      // broker has seen at least one store connection per retry line and never a callout or reader
      // connection for E, so no callout for E, a service-endpoint one included, ever reached this host.
      const storeOpens = (await everNamed(`cotal:auth-replica-store:${E.name}`)).length;
      check("each retry of the refused space opened its store connection, and never its reader or callout connection",
        storeOpens >= retries() && (await everNamed(`cotal:auth-replica-reader:${E.name}`)).length === 0 && (await everNamed(`cotal:auth-callout-replica:${E.name}`)).length === 0,
        { storeOpens, retries: retries() });
      // ---- retrying the refused space holds nothing over time ----------------------------------------
      // Samples every 10 s: the host's open descriptors and RSS, and the broker's live connections the
      // host holds for the plain spaces and for E. A retry in flight holds at most E's store connection.
      const hostPid = mixed.child.pid!;
      const liveConns = async () => {
        const names = (await connz()).connections.map((c) => c.name ?? "").filter((n) => n.startsWith("cotal:auth-replica") || n.startsWith("cotal:auth-callout-replica"));
        return { plain: names.filter((n) => !n.endsWith(`:${E.name}`)).length, refused: names.filter((n) => n.endsWith(`:${E.name}`)).length };
      };
      const soakRetries0 = retries();
      const samples: Array<{ s: number; fds: number; rssMb: number; plain: number; refused: number }> = [];
      const soakStart = Date.now();
      while (Date.now() - soakStart < SOAK * 1000) {
        const conns = await liveConns();
        samples.push({ s: Math.round((Date.now() - soakStart) / 1000), fds: readdirSync(`/proc/${hostPid}/fd`).length, rssMb: Number(rssMb(hostPid).toFixed(1)), ...conns });
        await wait(10_000);
      }
      const soakRetries = retries() - soakRetries0;
      const third = Math.max(1, Math.floor(samples.length / 3));
      const mean = (xs: number[]) => xs.reduce((a, x) => a + x, 0) / xs.length;
      const rssGrowth = mean(samples.slice(-third).map((x) => x.rssMb)) - mean(samples.slice(0, third).map((x) => x.rssMb));
      const fdGrowth = Math.max(...samples.slice(-third).map((x) => x.fds)) - Math.max(...samples.slice(0, third).map((x) => x.fds));
      console.log(`  soak ${SOAK}s, ${soakRetries} retries of ${E.name}, load ${readFileSync("/proc/loadavg", "utf8").split(" ").slice(0, 3).join(" ")}: ${JSON.stringify(samples)}`);
      check(`the host retried the refused space throughout the ${SOAK}s soak`, soakRetries >= Math.floor(SOAK / 10), { retries: soakRetries });
      check("no sample holds more than one connection for the refused space, and the plain spaces' connections stay level",
        samples.every((x) => x.refused <= 1) && Math.max(...samples.map((x) => x.plain)) - Math.min(...samples.map((x) => x.plain)) <= 1,
        { refused: samples.map((x) => x.refused), plain: samples.map((x) => x.plain) });
      check("the host's open descriptors do not grow across the retries", fdGrowth <= 2, { fdGrowth, fds: samples.map((x) => x.fds) });
      check("the host's RSS does not grow across the retries", rssGrowth <= 16, { rssGrowthMb: Number(rssGrowth.toFixed(1)) });

      const primaryE = startDaemon("primary-again:E", ["--space", E.name, "--service-endpoints"]);
      await until(() => loadAuthServiceInfo(userAuthStateDir(root, E.name))?.pid === primaryE.child.pid || primaryE.child.exitCode !== null, `E's primary did not come up: ${primaryE.out.join("")}`);
      await connectOnce(E, E.bearers[0]);
      check("with its full service back the refused space connects, and its callout queue group is that service alone",
        JSON.stringify(await calloutMembers(E.name)) === JSON.stringify([`cotal:auth-service:${E.name}`]) && (await everNamed(`cotal:auth-callout-replica:${E.name}`)).length === 0,
        await calloutMembers(E.name));
      await stopDaemon("primary-again:E");
      const answers = Object.fromEntries(await Promise.all(spaces.map(async (s) => [s.name, await admitsServiceEndpoints({ space: s.name, server: servers, secrets: store })])));
      check("admitsServiceEndpoints answers true for the space the host retries and false for each space it answers",
        answers[E.name] === true && answers[spaces[0].name] === false && answers[spaces[1].name] === false, answers);
      await stopDaemon("mixed");
      const single = startDaemon("refused:single-E", ["--callout-only", "--space", E.name]);
      const singleCode = await exited(single.child);
      check("a single-space replica for the refused space still refuses at startup",
        singleCode !== 0 && single.out.join("").includes(`space "${E.name}" admits service endpoints`), single.out.join("").trim().slice(0, 200));

      // ---- one process, two spaces -----------------------------------------------------------------
      writeManifest([spaces[0].name, spaces[1].name]);
      const host = startDaemon("host", ["--callout-only", "--spaces", manifestPath]);
      await until(() => host.out.join("").includes("✓ auth callout host up") || host.child.exitCode !== null, `the host did not come up: ${host.out.join("")}`);
      if (host.child.exitCode !== null) throw new Error(`the host exited ${host.child.exitCode}: ${host.out.join("")}`);
      check("one process serves both spaces", host.out.join("").includes(`${spaces[0].name}, ${spaces[1].name}`), host.out.join("").trim().slice(0, 160));

      const a = await connectOnce(spaces[0], spaces[0].bearers[0]);
      const b = await connectOnce(spaces[1], spaces[1].bearers[0]);
      check("a connect on each space succeeds through the one process", true, { a: a.cid, b: b.cid });

      // ---- key isolation, read from the broker ------------------------------------------------------
      check("the two spaces hold different data accounts (the control for the binding check)",
        spaces[0].dataAccountPub !== spaces[1].dataAccountPub);
      check("a connection minted by space A's lane is bound into space A's data account, never space B's",
        a.account === spaces[0].dataAccountPub && a.account !== spaces[1].dataAccountPub, { bound: a.account, spaceA: spaces[0].dataAccountPub });
      check("a connection minted by space B's lane is bound into space B's data account, never space A's",
        b.account === spaces[1].dataAccountPub && b.account !== spaces[0].dataAccountPub, { bound: b.account, spaceB: spaces[1].dataAccountPub });

      // Space A's bearer presented to space B's callout: B's lane validates it against B's own
      // issuer and audience, so it is never minted by B's keys.
      let crossed: string | undefined;
      try {
        await connectOnce(spaces[1], spaces[0].bearers[0]);
      } catch (e) { crossed = e instanceof Error ? e.message : String(e); }
      check("a bearer for space A is refused by space B's lane", crossed !== undefined, crossed?.slice(0, 120));

      // The cells below ask which lane answers and whether one lane stops another, not how fast the
      // host is. The connect-load harness offers its rate whatever the service does, so it can
      // deliberately overload it, and on a shared host at a high load average the callout then
      // answers some connects with a signed timeout denial, which a client sees as
      // `Authorization Violation`. That is this box's capacity, not an isolation or continuity
      // failure, so these cells offer a rate with headroom and keep their zero-loss assertions
      // there, where a loss means what the cell says it means.
      const HEADROOM_RATE = Math.max(2, Math.round(RATE / 4));

      // ---- request routing: a space's callouts reach only its own lane -----------------------------
      const before = await calloutsByLane();
      const onlyA = await load(spaces[0], SECONDS, HEADROOM_RATE);
      const routed = delta(before, await calloutsByLane());
      check("every connect to space A succeeds", onlyA.ok === onlyA.attempts, onlyA.byReason);
      // Rate-independent, and non-vacuous: lane A's subscription counter must actually have moved,
      // so "B saw none" cannot pass by nothing being delivered to either lane.
      check("space A's callout requests reach space A's lane and never space B's",
        routed[spaces[0].name] > 0 && routed[spaces[0].name] >= onlyA.ok && (routed[spaces[1].name] ?? 0) === 0, routed);

      // ---- a lane removed while traffic flows to the other -----------------------------------------
      const beforeRemoval = await calloutsByLane();
      const removal = load(spaces[0], SECONDS, HEADROOM_RATE);
      await wait(500);
      writeManifest([spaces[0].name]);
      await until(() => host.out.join("").includes(`space "${spaces[1].name}" left the manifest`), `the host did not close the removed lane: ${host.out.join("").slice(-400)}`);
      const during = await removal;
      const acrossRemoval = delta(beforeRemoval, await calloutsByLane());
      check("the surviving lane kept answering across the removal", acrossRemoval[spaces[0].name] >= during.ok && during.ok > 0, acrossRemoval);
      check("removing a lane leaves the other lane answering every connect", during.ok === during.attempts, during.byReason);
      const afterRemove = await calloutsByLane();
      check("only the remaining space still holds a callout subscription", afterRemove[spaces[1].name] === undefined, Object.keys(afterRemove));
      const refusedB = await load(spaces[1], 2, 4);
      check("the removed space's connects are no longer answered by this process", refusedB.ok === 0, refusedB.byReason);

      // ---- a lane added while running ---------------------------------------------------------------
      writeManifest([spaces[0].name, spaces[1].name]);
      await until(() => host.out.join("").includes(`space "${spaces[1].name}" opened`), `the host did not reopen the lane: ${host.out.join("").slice(-400)}`);
      const readded = await load(spaces[1], 2, 4);
      check("a space added to the manifest is served again", readded.ok === readded.attempts, readded.byReason);

      // ---- a manifest that does not read whole keeps the live lanes --------------------------------
      const mark = host.out.join("").length;
      writeFileSync(manifestPath, '{"version": 1, "spaces": ["');
      await until(() => host.out.join("").slice(mark).includes("is invalid"), `the host did not report the invalid manifest: ${host.out.join("").slice(-400)}`);
      check("an invalid manifest is reported and the live lanes are kept",
        host.out.join("").slice(mark).includes("keeping the 2 lane(s) already open"), host.out.join("").slice(mark).trim().slice(0, 200));
      const stillUp = await loadAll(spaces.slice(0, 2), 2, 4);
      check("both lanes still answer after the invalid manifest", stillUp.ok === stillUp.attempts, stillUp.byReason);

      // ---- the manifest grammar ---------------------------------------------------------------------
      for (const [why, text] of [
        ["an object entry", '{"version":1,"spaces":[{"space":"a","server":"nats://x"}]}'],
        ["an unknown field", '{"version":1,"spaces":["a"],"server":"nats://x"}'],
        ["an empty list", '{"version":1,"spaces":[]}'],
        ["a duplicate space", '{"version":1,"spaces":["a","a"]}'],
        ["a wrong version", '{"version":2,"spaces":["a"]}'],
        ["a partial file", '{"version":1,"spaces":["a"'],
      ] as Array<[string, string]>) {
        let refusal: string | undefined;
        try { parseSpaceManifest(text); } catch (e) { refusal = e instanceof Error ? e.message : String(e); }
        check(`the manifest refuses ${why}`, refusal !== undefined, refusal?.slice(0, 100));
      }
      check("the manifest accepts the shape the host writes", parseSpaceManifest('{"version":1,"spaces":["a","b"]}').spaces.length === 2);

      await stopDaemon("host");
      complete = true;
    }
  } finally {
    for (const child of loads) { try { child.kill("SIGKILL"); } catch { /* already gone */ } }
    for (const label of [...daemons.keys()]) { try { await stopDaemon(label); } catch { /* already gone */ } }
    for (const { child } of daemons.values()) { try { child.kill("SIGKILL"); } catch { /* already gone */ } }
    releaseBroker?.();
    if (broker) { try { await killAndAwaitExit(broker, "SIGKILL"); } catch { /* already gone */ } }
    idp.close();
    try { rmSync(home, { recursive: true, force: true }); } catch { /* best effort */ }
  }
  if (!complete) throw new Error("callout-multi-tenant: did not reach the end");
  console.log(`callout-multi-tenant: ${passed} checks passed`);
}
