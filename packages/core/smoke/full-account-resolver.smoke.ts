import assert from "node:assert/strict";
import { spawn, type ChildProcess } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { connect, credsAuthenticator, type NatsConnection } from "@nats-io/transport-node";
import { decode, encodeAccount, encodeUser } from "@nats-io/jwt";
import { fromPublic, fromSeed } from "@nats-io/nkeys";
import { composeSpaceAuth, createBrokerAuth, createSpaceAccountAuth, credsFromJwt, isReachable, newIdentity, serverConfig } from "../src/index.js";
import { awaitBrokerReady, emitSentinel, freePort, killAndAwaitExit, SMOKE_BROKER_TOKEN, teardownOnSignal, teardownPathOnSignal } from "@cotal-ai/smoke-kit";

const dir = await mkdtemp(join(tmpdir(), SMOKE_BROKER_TOKEN + "full-resolver-")), releasePath = teardownPathOnSignal(dir);
const clients: NatsConnection[] = [], children: ChildProcess[] = [], releases: Array<() => void> = [];
const enc = (s: string) => new TextEncoder().encode(s);
let passed = 0, failed = 0;
const cell = async (name: string, run: () => Promise<void>) => {
  try { await run(); passed++; console.log(`  ✓ ${name}`); }
  catch (e) { failed++; console.error(`  ✗ ${name}: ${e instanceof Error ? e.message : String(e)}`); }
};
try {
  const broker = await createBrokerAuth("full-resolver-fixture"), account = await createSpaceAccountAuth(broker, "full-resolver-fixture");
  const extra = await createSpaceAccountAuth(broker, "extra-resolver-fixture"), auth = composeSpaceAuth(broker, account);
  const opts: Parameters<typeof serverConfig>[2] = { transport: { kind: "plaintext" }, storeDir: join(dir, "js"), maxFileStore: 64 * 1024 * 1024,
    extraAccounts: [{ pub: extra.account.pub, jwt: extra.account.jwt }] };
  const full = { kind: "full" as const, directory: join(dir, "account-jwts"), limit: 100, intervalMs: 120_000 };
  const config = (accountResolver?: Parameters<typeof serverConfig>[2]["accountResolver"]) => serverConfig(broker, [account], { ...opts, accountResolver });
  await cell("default and explicit memory render the same existing configuration", async () => {
    const original = `# Generated by \`cotal up\` - do not edit by hand.
host: 127.0.0.1
port: 4222
max_control_line: 65536
jetstream { store_dir: ${JSON.stringify(opts.storeDir)}, max_file_store: ${opts.maxFileStore} }
operator: ${broker.operator.jwt}
system_account: ${broker.sys.pub}
resolver: MEMORY
resolver_preload: {
  ${account.account.pub}: ${account.account.jwt}
  ${broker.sys.pub}: ${broker.sys.jwt}
  ${extra.account.pub}: ${extra.account.jwt}
}
`;
    assert.equal(config(), original); assert.equal(config({ kind: "memory" }), original);
  });
  await cell("full renderer keeps data system and extra account preloads", async () => {
    const text = config(full); for (const jwt of [account.account.jwt, broker.sys.jwt, extra.account.jwt]) assert.ok(text.includes(jwt));
  });
  await cell("full renderer emits native capacity interval and no-delete settings", async () => {
    const text = config(full); assert.match(text, /type: full/); assert.match(text, /allow_delete: false/); assert.match(text, /interval: "120000ms"/); assert.match(text, /limit: 100/);
  });
  await cell("unknown null and expanded memory options refuse instead of falling back", async () => {
    const inherited = Object.assign(Object.create({ kind: "memory" }) as Record<string, unknown>, { unknown: true });
    for (const value of [null, [], {}, { kind: "cache" }, { kind: "memory", directory: full.directory }, inherited])
      assert.throws(() => config(value as typeof full), /account resolver options are invalid/);
  });
  await cell("relative empty and control-character directories refuse", async () => {
    for (const directory of ["", "relative/jwt", "\n" + full.directory, full.directory + "\0"])
      assert.throws(() => config({ ...full, directory }), /account resolver options are invalid/);
  });
  await cell("zero and fractional native capacity refuse", async () => {
    for (const limit of [0, -1, 1.5]) assert.throws(() => config({ ...full, limit }), /account resolver options are invalid/);
  });
  await cell("subsecond fractional and over-day synchronization intervals refuse", async () => {
    for (const intervalMs of [0, 999, 1000.5, 86_400_001]) assert.throws(() => config({ ...full, intervalMs }), /account resolver options are invalid/);
  });
  await cell("unknown full options refuse before rendering", async () => {
    assert.throws(() => config({ ...full, allowDelete: true } as typeof full), /account resolver options are invalid/);
  });
  for (const mode of ["memory", "full"] as const) {
    const port = await freePort(), servers = `nats://127.0.0.1:${port}`, store = join(dir, mode + '-jwt-"\\path');
    const text = serverConfig(broker, [account], { ...opts, port, storeDir: join(dir, mode + '-js'),
      accountResolver: mode === "full" ? { ...full, directory: store } : { kind: "memory" } });
    const file = join(dir, mode + '.conf'); await writeFile(file, text, { mode: 0o600 });
    const start = async () => {
      const child = spawn("nats-server", ["-c", file], { stdio: ["ignore", "ignore", "pipe"] });
      children.push(child); const release = teardownOnSignal(child); releases.push(release);
      assert.ok(child.pid); console.log(`owned resolver broker started pid=${child.pid} mode=${mode}`);
      let log = ""; child.stderr!.on("data", b => { log = (log + String(b)).slice(-4000); });
      await awaitBrokerReady(() => isReachable(servers), { servers, attempts: 50, delayMs: 100, output: () => log }); return { child, release };
    };
    let running = await start();
    const target = newIdentity(), other = newIdentity(), admin = newIdentity(), expiresAt = Math.floor(Date.now() / 1000) + 240;
    const user = async (id: ReturnType<typeof newIdentity>, system = false) => credsFromJwt(await encodeUser('resolver-fixture-user', fromPublic(id.id), fromPublic(system ? auth.sys.pub : auth.account.pub),
      { pub: system ? { allow: [`$SYS.REQ.ACCOUNT.${auth.account.pub}.CLAIMS.UPDATE`] } : { deny: [">"] }, sub: { allow: [`_INBOX_${id.id}.>`] } },
      { exp: expiresAt, signer: fromSeed(enc(system ? auth.sys.signingSeed! : auth.account.signingSeed!)) }), id);
    const targetCreds = await user(target), otherCreds = await user(other), adminCreds = await user(admin, true);
    const dial = async (creds: string, id: ReturnType<typeof newIdentity>) => {
      assert.ok(Math.floor(Date.now() / 1000) < expiresAt);
      const nc = await connect({ servers, authenticator: credsAuthenticator(enc(creds)), inboxPrefix: `_INBOX_${id.id}`, name: id.id, reconnect: false, timeout: 3000 });
      clients.push(nc); await nc.flush(); return nc;
    };
    const held = await dial(targetCreds, target), unaffected = await dial(otherCreds, other), curator = await dial(adminCreds, admin);
    const original = decode<Record<string, unknown>>(auth.account.jwt), deadline = Date.now() + 6000;
    while (Math.floor(Date.now() / 1000) <= original.iat) { assert.ok(Date.now() < deadline); await new Promise(r => setTimeout(r, 50)); }
    const updated = await encodeAccount(original.name, fromPublic(auth.account.pub), { ...original.nats, revocations: { [target.id]: Math.floor(Date.now() / 1000) } }, { signer: fromSeed(enc(auth.operator.seed!)) });
    await cell(`${mode} native update closes and denies only the target key`, async () => {
      const response = (await curator.request(`$SYS.REQ.ACCOUNT.${auth.account.pub}.CLAIMS.UPDATE`, enc(updated), { timeout: 3000 })).json<{ data: { account: string; code: number; message: string } }>();
      assert.equal(response.data.account, auth.account.pub); assert.equal(response.data.code, 200); assert.equal(response.data.message, "jwt updated");
      await Promise.race([held.closed(), new Promise((_, reject) => { const timer = setTimeout(() => reject(new Error("target holder survived native update")), 2000); timer.unref(); })]);
      await assert.rejects(dial(targetCreds, target), /authorization|authentication|revoked/i); await unaffected.flush(); assert.equal(unaffected.isClosed(), false);
    });
    if (mode === "full") await cell("native full resolver stores the submitted signed claim", async () => { assert.equal(await readFile(join(store, auth.account.pub + '.jwt'), 'utf8'), updated); });
    for (const c of clients.splice(0).reverse()) await c.close();
    await killAndAwaitExit(running.child, 'SIGTERM'); assert.ok(running.child.exitCode !== null || running.child.signalCode !== null); running.release();
    assert.equal(await readFile(file, 'utf8'), text); running = await start();
    await cell(`${mode} restart keeps the original preload and observed key policy`, async () => {
      assert.ok(text.includes(auth.account.jwt));
      if (mode === "full") await assert.rejects(dial(targetCreds, target), /authorization|authentication|revoked/i);
      else { const c = await dial(targetCreds, target); assert.equal(c.isClosed(), false); }
      const c = await dial(otherCreds, other); await c.flush(); assert.equal(c.isClosed(), false);
    });
    if (mode === "full") await cell("native full resolver retains newer claim bytes after restart", async () => { assert.equal(await readFile(join(store, auth.account.pub + '.jwt'), 'utf8'), updated); });
    for (const c of clients.splice(0).reverse()) await c.close();
    await killAndAwaitExit(running.child, 'SIGTERM'); assert.ok(running.child.exitCode !== null || running.child.signalCode !== null); running.release();
  }
} finally {
  for (const c of clients.reverse()) await c.close();
  for (const c of children) {
    await killAndAwaitExit(c, 'SIGTERM'); assert.ok(c.exitCode !== null || c.signalCode !== null, "owned broker remains live");
    console.log(`owned resolver broker stopped pid=${c.pid} exit=${c.exitCode} signal=${c.signalCode}`);
  }
  for (const release of releases) release(); await rm(dir, { recursive: true, force: true }); releasePath();
}
emitSentinel({ passed, failed }); if (failed) process.exitCode = 1;
