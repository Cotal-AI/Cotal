// Adding and retiring a space account on a running broker, against a real nats-server.
//
// With the default MEMORY resolver a pushed claim for an account the broker has not loaded is
// answered "jwt update skipped", so adding a space means rewriting the config and reloading. With
// `accountResolver: { kind: "full" }` the same push is accepted and the new account's user
// connects at once, with no reload and without disturbing a resident account's connection. The
// pushed claim survives a restart, and a retired claim closes the account's live connection and
// refuses its users, before and after a restart.
import assert from "node:assert/strict";
import { spawn, type ChildProcess } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { connect, credsAuthenticator, type NatsConnection } from "@nats-io/transport-node";
import { encodeUser } from "@nats-io/jwt";
import { fromPublic, fromSeed } from "@nats-io/nkeys";
import {
  createBrokerAuth, createSpaceAccountAuth, credsFromJwt, isReachable, newIdentity, pushAccountClaim, retireAccountClaim,
  serverConfig, type AccountResolver, type SpaceAccountAuth,
} from "../src/index.js";
import { awaitBrokerReady, emitSentinel, freePort, killAndAwaitExit, SMOKE_BROKER_TOKEN, teardownOnSignal, teardownPathOnSignal } from "@cotal-ai/smoke-kit";

const dir = await mkdtemp(join(tmpdir(), SMOKE_BROKER_TOKEN + "full-resolver-")), releasePath = teardownPathOnSignal(dir);
const clients: NatsConnection[] = [], children: ChildProcess[] = [], releases: Array<() => void> = [];
const enc = (s: string) => new TextEncoder().encode(s);
const nowSeconds = () => Math.floor(Date.now() / 1000);
const nextSecond = async () => { const start = nowSeconds(); while (nowSeconds() === start) await new Promise((r) => setTimeout(r, 25)); };
let passed = 0, failed = 0;
const cell = async (name: string, run: () => Promise<void>) => {
  try { await run(); passed++; console.log(`  ✓ ${name}`); }
  catch (e) { failed++; console.error(`  ✗ ${name}: ${e instanceof Error ? e.message : String(e)}`); }
};

try {
  const broker = await createBrokerAuth("full-resolver-fixture");
  const resident = await createSpaceAccountAuth(broker, "resident"), arrival = await createSpaceAccountAuth(broker, "arrival");
  const base = { transport: { kind: "plaintext" } as const, storeDir: join(dir, "js"), maxFileStore: 64 * 1024 * 1024 };
  const full = { kind: "full" as const, directory: join(dir, "account-jwts"), limit: 100, intervalMs: 120_000 };
  const render = (accountResolver?: AccountResolver) => serverConfig(broker, [resident], { ...base, accountResolver });

  await cell("omitted and explicit memory render the existing configuration byte for byte", async () => {
    const existing = `# Generated by \`cotal up\` - do not edit by hand.
host: 127.0.0.1
port: 4222
max_control_line: 65536
jetstream { store_dir: ${JSON.stringify(base.storeDir)}, max_file_store: ${base.maxFileStore} }
operator: ${broker.operator.jwt}
system_account: ${broker.sys.pub}
resolver: MEMORY
resolver_preload: {
  ${resident.account.pub}: ${resident.account.jwt}
  ${broker.sys.pub}: ${broker.sys.jwt}
}
`;
    assert.equal(render(), existing);
    assert.equal(render({ kind: "memory" }), existing);
  });
  await cell("full renders the native directory resolver with deletion off and keeps the preloads", async () => {
    const text = render({ ...full, directory: join(dir, 'odd "dir"') });
    assert.ok(text.includes(`resolver: { type: full, dir: ${JSON.stringify(join(dir, 'odd "dir"'))}, allow_delete: false, interval: "120000ms", limit: 100 }\n`));
    for (const jwt of [resident.account.jwt, broker.sys.jwt]) assert.ok(text.includes(jwt));
  });
  await cell("malformed resolver options refuse instead of falling back to memory", async () => {
    const inherited = Object.assign(Object.create({ kind: "memory" }) as Record<string, unknown>, { extra: true });
    for (const value of [null, [], {}, { kind: "cache" }, { kind: "memory", directory: full.directory }, inherited, { ...full, allowDelete: true },
      { ...full, directory: "relative" }, { ...full, directory: full.directory + "\n" }, { ...full, limit: 0 }, { ...full, limit: 1.5 },
      { ...full, intervalMs: 999 }, { ...full, intervalMs: 86_400_001 }])
      assert.throws(() => render(value as AccountResolver), /accountResolver must be/);
  });
  await cell("retireAccountClaim refuses an account another operator signed", async () => {
    const foreign = await createSpaceAccountAuth(await createBrokerAuth("foreign"), "foreign");
    await assert.rejects(retireAccountClaim(broker, foreign.account.jwt, nowSeconds()), /not signed by this broker's operator/);
  });
  await cell("pushAccountClaim refuses malformed input before sending anything", async () => {
    let sent = 0;
    const nc = { requestMany: async () => { sent++; return [][Symbol.iterator]() as never; } };
    const id = "N" + "A".repeat(55);
    for (const input of [
      { accountJwt: arrival.account.jwt, expectedServerIds: [], maxWaitMs: 1000 },
      { accountJwt: arrival.account.jwt, expectedServerIds: [id, id], maxWaitMs: 1000 },
      { accountJwt: arrival.account.jwt, expectedServerIds: ["not-a-server"], maxWaitMs: 1000 },
      { accountJwt: arrival.account.jwt, expectedServerIds: [id], maxWaitMs: 30_001 },
      { accountJwt: broker.operator.jwt, expectedServerIds: [id], maxWaitMs: 1000 },
    ]) await assert.rejects(pushAccountClaim(nc, input), /pushAccountClaim:/);
    assert.equal(sent, 0);
  });

  for (const mode of ["memory", "full"] as const) {
    const port = await freePort(), servers = `nats://127.0.0.1:${port}`;
    const resolver: AccountResolver = mode === "full" ? full : { kind: "memory" };
    const file = join(dir, `${mode}.conf`);
    await writeFile(file, serverConfig(broker, [resident], { ...base, port, storeDir: join(dir, `${mode}-js`), accountResolver: resolver }), { mode: 0o600 });
    let log = "";
    const start = async () => {
      const child = spawn("nats-server", ["-c", file], { stdio: ["ignore", "ignore", "pipe"] });
      children.push(child); releases.push(teardownOnSignal(child)); assert.ok(child.pid);
      child.stderr!.on("data", (b) => { log = (log + String(b)).slice(-20_000); });
      await awaitBrokerReady(() => isReachable(servers), { servers, attempts: 50, delayMs: 100, output: () => log });
      return child;
    };
    const stop = async (child: ChildProcess) => {
      for (const c of clients.splice(0).reverse()) await c.close();
      await killAndAwaitExit(child, "SIGTERM"); assert.ok(child.exitCode !== null || child.signalCode !== null, "owned broker remains live");
    };
    const userCreds = async (account: SpaceAccountAuth) => {
      const id = newIdentity();
      const jwt = await encodeUser("resolver-fixture-user", fromPublic(id.id), fromPublic(account.account.pub),
        { pub: { deny: [">"] }, sub: { allow: [`_INBOX_${id.id}.>`] } },
        { exp: nowSeconds() + 600, signer: fromSeed(enc(account.account.signingSeed)) });
      return { creds: credsFromJwt(jwt, id), id: id.id };
    };
    const systemCreds = async () => {
      const id = newIdentity();
      const jwt = await encodeUser("resolver-fixture-system", fromPublic(id.id), fromPublic(broker.sys.pub),
        { pub: { allow: ["$SYS.REQ.ACCOUNT.*.CLAIMS.UPDATE"] }, sub: { allow: [`_INBOX_${id.id}.>`] } },
        { exp: nowSeconds() + 600, signer: fromSeed(enc(broker.sys.signingSeed!)) });
      return { creds: credsFromJwt(jwt, id), id: id.id };
    };
    const dial = async (user: { creds: string; id: string }) => {
      const nc = await connect({ servers, authenticator: credsAuthenticator(enc(user.creds)), inboxPrefix: `_INBOX_${user.id}`, reconnect: false, timeout: 3000 });
      clients.push(nc); await nc.flush(); return nc;
    };
    const residentUser = await userCreds(resident), arrivalUser = await userCreds(arrival), system = await systemCreds();
    // A user the retired account mints later is refused by its zero connection limit. Depending on
    // timing, nats-server's -ERR or its socket close reaches the client first, so the refusal is
    // asserted and its text only logged; the resident dialed next proves the broker still serves.
    const refusedLater = async () => {
      const refusal = await dial(await userCreds(arrival)).then(() => undefined, (e: unknown) => e);
      assert.ok(refusal !== undefined, "a user minted after retirement connected");
      console.log(`    later user refused: ${refusal instanceof Error ? `${refusal.name} ${(refusal as { code?: string }).code ?? ""} ${refusal.message}`.trim() : String(refusal)}`);
      await dial(residentUser);
    };
    let running = await start();
    const held = await dial(residentUser), curator = await dial(system);
    const serverId = curator.info!.server_id;
    const push = (accountJwt: string) => pushAccountClaim(curator, { accountJwt, expectedServerIds: [serverId], maxWaitMs: 3000 });

    if (mode === "memory") {
      await cell("memory: a pushed new account is answered 'jwt update skipped' and its user stays refused", async () => {
        await assert.rejects(push(arrival.account.jwt), /jwt update skipped/);
        await assert.rejects(dial(arrivalUser), /authorization|authentication/i);
      });
      await stop(running);
      continue;
    }

    await cell("full: a new account is accepted and its user connects with no reload, the resident connection untouched", async () => {
      const t0 = performance.now();
      const ack = await push(arrival.account.jwt);
      const acked = performance.now();
      assert.deepEqual(ack, { account: arrival.account.pub, acknowledgedServerIds: [serverId] });
      await dial(arrivalUser);
      console.log(`    push acknowledged in ${(acked - t0).toFixed(1)} ms, new user connected ${(performance.now() - acked).toFixed(1)} ms later`);
      assert.doesNotMatch(log, /Reloaded server configuration|Trapped "hangup"/);
      await held.flush(); assert.equal(held.isClosed(), false);
    });
    await cell("full: the pushed claim is stored in the resolver directory", async () => {
      assert.equal(await readFile(join(full.directory, `${arrival.account.pub}.jwt`), "utf8"), arrival.account.jwt);
    });
    await stop(running); running = await start();
    await cell("full: a restart keeps the pushed account, which its config does not list", async () => {
      await dial(arrivalUser); await dial(residentUser);
    });

    const live = await dial(arrivalUser), keeper = await dial(residentUser), curator2 = await dial(system);
    await nextSecond();
    const retired = await retireAccountClaim(broker, arrival.account.jwt, nowSeconds());
    await cell("full: a retired claim closes the account's live connection and refuses its users; the resident stays", async () => {
      const restartedId = curator2.info!.server_id; // a restarted nats-server has a new server id
      const ack = await pushAccountClaim(curator2, { accountJwt: retired, expectedServerIds: [restartedId], maxWaitMs: 3000 });
      assert.deepEqual(ack.acknowledgedServerIds, [restartedId]);
      await Promise.race([live.closed(), new Promise((_, reject) => setTimeout(() => reject(new Error("the retired account's connection stayed open")), 3000).unref())]);
      await assert.rejects(dial(arrivalUser), /authorization|authentication|revoked/i);
      await nextSecond();
      await refusedLater();
      await keeper.flush(); assert.equal(keeper.isClosed(), false);
    });
    await stop(running); running = await start();
    await cell("full: a restart keeps the account retired and the resident usable", async () => {
      await refusedLater();
    });
    await stop(running);
  }
} finally {
  for (const c of clients.reverse()) await c.close();
  for (const c of children) {
    await killAndAwaitExit(c, "SIGTERM");
    assert.ok(c.exitCode !== null || c.signalCode !== null, "owned broker remains live");
  }
  for (const release of releases) release();
  await rm(dir, { recursive: true, force: true }); releasePath();
}
emitSentinel({ passed, failed });
if (failed) process.exitCode = 1;
