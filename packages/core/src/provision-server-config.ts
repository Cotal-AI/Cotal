import { isAbsolute } from "node:path";
import type { BrokerTransport } from "./broker-tls.js";
import { MAX_CONTROL_LINE_BYTES, assertAccountSignedByBroker } from "./provision-jwt.js";
import type { BrokerAuth, SpaceAccountAuth } from "./provision-jwt.js";


/**
 * Render the config for an OPEN (no-auth) broker.
 *
 * This exists so that no path reaches a listener without naming its transport. Open mode used to
 * start nats-server from bare CLI flags (`-js -sd … -p … -a …`) and never called `serverConfig` at
 * all, which meant the required `transport` union protected the auth path and was silent on the
 * open one: an operator could pass a cert and key, watch `up` print its normal banner, and get a
 * cleartext listener. That is the silent downgrade this feature exists to prevent, reachable by
 * someone who did everything right — so open mode renders a config too.
 *
 * It deliberately does NOT reuse `serverConfig`: that renders the operator, system account and
 * MEMORY resolver, none of which a no-auth broker should carry. What the two share is the thing
 * that matters — a REQUIRED transport, so the choice cannot be omitted on either path.
 *
 * IMPORTANT, and it must be said wherever open-mode TLS is surfaced to an operator: TLS ON AN
 * OPEN MESH GIVES CONFIDENTIALITY, NOT AUTHENTICATION. It hides traffic from a passive observer.
 * It does not verify who is connecting, because an open broker has no credentials to check — so
 * anyone who can reach the port still gets in, encrypted. It is a legitimate configuration for a
 * mesh crossing a network nobody controls, and it is NOT "secure" in the sense a reader will
 * assume from seeing `cotals://`. Describe it as the caveat it is rather than as a feature.
 */
export function openServerConfig(opts: {
  port?: number;
  host?: string;
  storeDir: string;
  /** Version of the broker this configuration targets. Enables version-specific JetStream limits. */
  brokerVersion?: string;
  /** JetStream file storage cap in bytes (`max_file_store`). Omitted leaves nats-server's dynamic
   *  default. nats-server fixes the cap at start and refuses a reload that changes it. */
  maxFileStore?: number;
  /** Native broker message size limit in bytes. Omitted leaves nats-server's default. */
  maxPayload?: number;
  /** Native nats-server file logging and rotation. Rotation bounds require {@link logFile}. */
  logFile?: string;
  logfileSizeLimit?: number;
  logfileMaxNum?: number;
  transport: BrokerTransport;
}): string {
  const port = opts.port ?? 4222;
  const host = opts.host ?? "127.0.0.1";
  const logBlock = renderLogBlock("openServerConfig", opts);
  if (opts.maxPayload !== undefined && (!Number.isSafeInteger(opts.maxPayload) || opts.maxPayload <= 0))
    throw new Error("openServerConfig: maxPayload must be a positive safe integer of bytes");
  return `# Generated by \`cotal up\` - do not edit by hand.
host: ${host}
port: ${port}
max_control_line: ${MAX_CONTROL_LINE_BYTES}
${opts.maxPayload !== undefined ? `max_payload: ${opts.maxPayload}\n` : ""}${logBlock}${renderTlsBlock(opts.transport)}${renderJetStreamBlock("openServerConfig", opts.storeDir, opts.maxFileStore, opts.brokerVersion)}
`;
}

/** Render native nats-server file logging and rotation directives when requested. */
function renderLogBlock(renderer: string, opts: { logFile?: string; logfileSizeLimit?: number; logfileMaxNum?: number }): string {
  if (opts.logFile === undefined && (opts.logfileSizeLimit !== undefined || opts.logfileMaxNum !== undefined))
    throw new Error(`${renderer}: logfileSizeLimit and logfileMaxNum require logFile`);
  const lines: string[] = [];
  if (opts.logFile !== undefined) {
    if (!opts.logFile.trim() || /[\u0000-\u001f\u007f]/u.test(opts.logFile))
      throw new Error(`${renderer}: logFile must be a non-empty path without control characters`);
    lines.push(`log_file: ${JSON.stringify(opts.logFile)}`);
  }
  if (opts.logfileSizeLimit !== undefined) {
    if (!Number.isSafeInteger(opts.logfileSizeLimit) || opts.logfileSizeLimit <= 0)
      throw new Error(`${renderer}: logfileSizeLimit must be a positive integer number of bytes`);
    lines.push(`logfile_size_limit: ${opts.logfileSizeLimit}`);
  }
  if (opts.logfileMaxNum !== undefined) {
    if (!Number.isSafeInteger(opts.logfileMaxNum) || opts.logfileMaxNum <= 0)
      throw new Error(`${renderer}: logfileMaxNum must be a positive integer file count`);
    lines.push(`logfile_max_num: ${opts.logfileMaxNum}`);
  }
  return lines.length ? `${lines.join("\n")}\n` : "";
}

/** The exact `jetstream{}` block both broker renderers write for this store and cap, for a caller
 *  that must find or replace it in a rendered configuration. */
export function brokerJetStreamBlock(storeDir: string, maxFileStore?: number, brokerVersion?: string): string {
  return renderJetStreamBlock("brokerJetStreamBlock", storeDir, maxFileStore, brokerVersion);
}

/** The shared JetStream block. A set file cap must be positive; brokers 2.15 and later
 *  also need an explicit unlimited default consumer count. */
function renderJetStreamBlock(renderer: string, storeDir: string, maxFileStore: number | undefined, brokerVersion?: string): string {
  const version = brokerVersion === undefined ? undefined : /^(\d+)\.(\d+)\.\d+/.exec(brokerVersion);
  if (brokerVersion !== undefined && !version) throw new Error(`${renderer}: invalid brokerVersion ${JSON.stringify(brokerVersion)}`);
  const limits = version && (Number(version[1]) > 2 || Number(version[1]) === 2 && Number(version[2]) >= 15)
    ? ", limits { default_max_consumers: -1 }" : "";
  if (maxFileStore === undefined) return `jetstream { store_dir: ${JSON.stringify(storeDir)}${limits} }`;
  if (!Number.isSafeInteger(maxFileStore) || maxFileStore <= 0)
    throw new Error(`${renderer}: maxFileStore must be a positive integer number of bytes (got ${String(maxFileStore)})`);
  return `jetstream { store_dir: ${JSON.stringify(storeDir)}, max_file_store: ${maxFileStore}${limits} }`;
}

/** The one place a `tls{}` block is produced, shared by both broker renderers.
 *
 *  `allow_non_tls` is deliberately never emitted. It is a TOP-LEVEL knob (nested inside `tls{}`
 *  nats-server rejects it as an unknown field), and it turns the listener into mixed mode: INFO
 *  then advertises `tls_available` instead of `tls_required`, and a client that declines to
 *  upgrade is served in cleartext — precisely the credential exposure this transport closes.
 *  There is no supported migration mode; enabling TLS is all-or-nothing. */
function renderTlsBlock(transport: BrokerTransport): string {
  if (transport.kind === "plaintext") return "";
  return `tls {
  cert_file: ${JSON.stringify(transport.certFile)}
  key_file: ${JSON.stringify(transport.keyFile)}
}
`;
}

/** How the broker resolves account JWTs. `memory`, the default, is the static preload map, so adding
 *  or removing an account rewrites the whole config and reloads the broker. `full` is nats-server's
 *  directory resolver: it keeps each account's operator-signed claim in `directory` (at most `limit`
 *  of them, synchronized every `intervalMs`) and takes new or updated claims at run time from
 *  {@link pushAccountClaim}, with no reload. Native deletion stays off; {@link retireAccountClaim}
 *  stops an account instead. nats-server refuses to switch resolvers on a reload, so moving a broker
 *  between the two is a restart. */
export type AccountResolver =
  | { kind: "memory" }
  | { kind: "full"; directory: string; limit: number; intervalMs: number };

function renderAccountResolver(resolver: AccountResolver | undefined): string {
  if (resolver === undefined) return "resolver: MEMORY\n";
  const keys = resolver !== null && typeof resolver === "object" && !Array.isArray(resolver) ? Object.keys(resolver) : [];
  if (keys.length === 1 && keys[0] === "kind" && resolver.kind === "memory") return "resolver: MEMORY\n";
  if (keys.length !== 4 || resolver.kind !== "full" || !["kind", "directory", "limit", "intervalMs"].every((k) => keys.includes(k)) ||
      typeof resolver.directory !== "string" || !isAbsolute(resolver.directory) || /[\0\r\n]/.test(resolver.directory) ||
      !Number.isSafeInteger(resolver.limit) || resolver.limit < 1 ||
      !Number.isSafeInteger(resolver.intervalMs) || resolver.intervalMs < 1000 || resolver.intervalMs > 86_400_000)
    throw new Error('serverConfig: accountResolver must be { kind: "memory" } or { kind: "full", directory, limit, intervalMs } with an absolute directory, a positive whole limit and an interval of 1000 to 86400000 ms');
  return `resolver: { type: full, dir: ${JSON.stringify(resolver.directory)}, allow_delete: false, interval: "${resolver.intervalMs}ms", limit: ${resolver.limit} }\n`;
}

/** Render the `nats-server` config that trusts ONE broker operator and serves N spaces' accounts,
 *  resolved by MEMORY unless {@link AccountResolver} `full` is chosen.
 *
 *  Broker trust (operator + system account) comes from `broker` and has exactly one owner; the
 *  per-space data accounts are listed in `spaces`. Every space account is asserted to be signed by
 *  THIS broker's operator before it is preloaded: rendering a foreign-signed account would either
 *  refuse broker boot or, worse, advertise a tenant the broker cannot actually authenticate.
 *
 *  NOTE: the MEMORY resolver is one static whole-broker map, so every mutation rewrites all of
 *  it. With the `full` resolver the preloads seed its directory at boot, and nats-server keeps a
 *  newer pushed claim over an older preload, so a later render does not undo a push. Concurrent
 *  add/remove of spaces needs a broker-authoritative inventory with generation/CAS and atomic
 *  promotion above this function; this renderer is deliberately pure. */
export function serverConfig(
  broker: BrokerAuth,
  spaces: readonly SpaceAccountAuth[],
  opts: {
    port?: number;
    host?: string;
    storeDir: string;
    /** Version of the broker this configuration targets. Enables version-specific JetStream limits. */
    brokerVersion?: string;
    /** JetStream file storage cap in bytes (`max_file_store`). Omitted leaves nats-server's dynamic
     *  default. nats-server fixes the cap at start and refuses a reload that changes it. */
    maxFileStore?: number;
    /** Native nats-server file logging and rotation. Rotation bounds require {@link logFile}. */
    logFile?: string;
    logfileSizeLimit?: number;
    logfileMaxNum?: number;
    /** Explicit broker-wide payload limit. Omitted preserves nats-server's default. */
    maxPayload?: number;
    /** How long nats-server waits for an auth callout's answer, in whole seconds, rendered as
     *  `authorization { timeout: N }`. Omitted renders no block and leaves nats-server's default. An
     *  auth callout serving this broker must use the same value as its deadline. */
    authTimeout?: number;
    /** Account resolution; omitted is MEMORY, byte-identical to `{ kind: "memory" }`. */
    accountResolver?: AccountResolver;
    /** Additional operator-signed accounts to preload in the resolver — e.g. the dedicated
     *  auth-callout account (`@cotal-ai/auth`), which must never share the data account. */
    extraAccounts?: Array<{ pub: string; jwt: string }>;
    /** How the client port is served. REQUIRED, and required on purpose: an optional TLS field
     *  would let any future path that regenerates this config omit it and silently render a
     *  plaintext listener. Callers must say `{ kind: "plaintext" }` when that is what they mean.
     *  TLS is listener-wide, so it lives here in the broker options rather than per space —
     *  no space can enable, disable or rotate it independently. */
    transport: BrokerTransport;
    /** OPT-IN NATS websocket listener port: browsers cannot speak raw NATS TCP, so the
     *  console session client (a real mesh caller) needs one. This is a NEW ATTACK SURFACE the broker
     *  did not have — emitted only when set, DEFAULT-BOUND TO LOCALHOST ({@link wsHost}), no TLS
     *  (dev loopback; a remote/TLS dashboard is a later explicit opt-in). Omit it and no listener
     *  exists (a broker with no console need adds no surface). */
    wsPort?: number;
    /** Bind host for the websocket listener; defaults to loopback. Widening it (a remote dashboard)
     *  is a deliberate operator choice, never the default. */
    wsHost?: string;
  },
): string {
  if (!spaces.length) throw new Error("serverConfig: at least one space account is required");
  for (const s of spaces) assertAccountSignedByBroker(broker, s);
  const seen = new Map<string, string>();
  for (const s of [...spaces.map((s) => ({ pub: s.account.pub, what: `space "${s.space}"` })), ...(opts.extraAccounts ?? []).map((a) => ({ pub: a.pub, what: "an extra account" }))]) {
    const prior = seen.get(s.pub);
    if (prior) throw new Error(`serverConfig: account ${s.pub} is preloaded twice (${prior} and ${s.what}) - refusing to render an ambiguous resolver`);
    seen.set(s.pub, s.what);
  }
  const port = opts.port ?? 4222;
  const host = opts.host ?? "127.0.0.1";
  // The websocket listener: LOCALHOST by default, no_tls for the dev loopback. Emitted only
  // when wsPort is set — a broker with no console session client opens no ws surface.
  const websocket = opts.wsPort === undefined ? "" : `websocket {
  host: ${opts.wsHost ?? "127.0.0.1"}
  port: ${opts.wsPort}
  no_tls: true
}
`;
  // A minted "agent" carries its full permission allow-list inline in its user JWT, which the
  // client sends in the CONNECT protocol line. With per-channel + JetStream-API grants that JWT
  // exceeds the 4 KB default max_control_line at ~2 channels, and the server then silently drops
  // the connection (the client retries forever — a connect that "hangs"). Raise it to fit a rich
  // agent JWT — but right-sized, not generous: the CONNECT line is parsed BEFORE auth, so the cap
  // is a per-connection pre-auth allocation under connection flooding. See MAX_CONTROL_LINE_BYTES
  // for the derivation; mintCreds/mintPublicUserJwt refuse a JWT that would not fit it BEFORE this
  // config is ever reached, so a legal credential never depends on this margin alone.
  const tlsBlock = renderTlsBlock(opts.transport);
  const logBlock = renderLogBlock("serverConfig", opts);
  if (opts.maxPayload !== undefined && (!Number.isSafeInteger(opts.maxPayload) || opts.maxPayload <= 0))
    throw new Error("serverConfig: maxPayload must be a positive safe integer of bytes");
  if (opts.authTimeout !== undefined && (!Number.isSafeInteger(opts.authTimeout) || opts.authTimeout <= 0))
    throw new Error("serverConfig: authTimeout must be a positive whole number of seconds");
  return `# Generated by \`cotal up\` - do not edit by hand.
host: ${host}
port: ${port}
max_control_line: ${MAX_CONTROL_LINE_BYTES}
${opts.maxPayload === undefined ? "" : `max_payload: ${opts.maxPayload}\n`}${opts.authTimeout === undefined ? "" : `authorization { timeout: ${opts.authTimeout} }\n`}${logBlock}${tlsBlock}${renderJetStreamBlock("serverConfig", opts.storeDir, opts.maxFileStore, opts.brokerVersion)}
${websocket}operator: ${broker.operator.jwt}
system_account: ${broker.sys.pub}
${renderAccountResolver(opts.accountResolver)}resolver_preload: {
${spaces.map((s) => `  ${s.account.pub}: ${s.account.jwt}`).join("\n")}
  ${broker.sys.pub}: ${broker.sys.jwt}${(opts.extraAccounts ?? []).map((a) => `\n  ${a.pub}: ${a.jwt}`).join("")}
}
`;
}
