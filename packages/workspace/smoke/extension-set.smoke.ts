import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync, existsSync, renameSync, symlinkSync, unlinkSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { extensionInstallationRoot, extensionSetPaths, prepareExtensionSet, assertExtensionSetReadable, assertExtensionSetReady, holdExtensionSet, extensionSetCleanupSpec } from "../src/extension-set.js";

const root = mkdtempSync(join(tmpdir(), "extension-set-"));
process.env.XDG_CONFIG_HOME = join(root, "config");
const paths = extensionSetPaths();
assert.match(paths.id, /^[a-f0-9]{16}$/);
assert.equal(extensionInstallationRoot("/prefix/lib/node_modules/.pnpm/cotal-ai@1.2.3/node_modules/cotal-ai"), "/prefix/lib/node_modules/cotal-ai");
assert.equal(extensionInstallationRoot("/prefix/lib/node_modules/.pnpm/cotal-ai@2.0.0/node_modules/cotal-ai"), "/prefix/lib/node_modules/cotal-ai");
assert.notEqual(extensionInstallationRoot("/one/node_modules/cotal-ai"), extensionInstallationRoot("/two/node_modules/cotal-ai"));
assert.equal(extensionInstallationRoot("/prefix/lib/.cotal-generations/0123456789abcdef0123456789abcdef/cotal-ai"), "/prefix/lib/node_modules/cotal-ai");
assert.throws(assertExtensionSetReady, /missing or incomplete/);
const legacy = join(root, "config", "cotal", "extensions");
mkdirSync(legacy, { recursive: true });
const inventory = JSON.stringify({ extensions: [] });
writeFileSync(join(legacy, "extensions.json"), inventory);
const outside = join(root, "outside");
mkdirSync(outside);
mkdirSync(paths.root, { recursive: true, mode: 0o700 });
symlinkSync(outside, join(paths.root, "sets"), process.platform === "win32" ? "junction" : "dir");
await assert.rejects(prepareExtensionSet(async () => { throw new Error("must not reconcile through linked parent"); }), /symlink/);
assert.equal(existsSync(join(outside, paths.version)), false);
unlinkSync(join(paths.root, "sets"));
let attempts = 0;
await assert.rejects(prepareExtensionSet(async () => {
  attempts++;
  writeFileSync(join(paths.set, "unfinished"), "discard on retry");
  throw new Error("measured migration interruption");
}), /migration interruption/);
assert.throws(assertExtensionSetReady, /missing or incomplete/);
await assert.rejects(prepareExtensionSet(async () => { throw new Error("must not reconcile while installer lives"); }, { beforeReset: () => { throw new Error("live installer"); } }), /live installer/);
assert.equal(readFileSync(join(paths.set, "unfinished"), "utf8"), "discard on retry");
await prepareExtensionSet(async () => {
  attempts++;
  assert.equal(existsSync(join(paths.set, "unfinished")), false);
  assert.equal(readFileSync(join(paths.extensions, "extensions.json"), "utf8"), inventory);
});
assert.equal(attempts, 2);
assert.equal(readFileSync(join(legacy, "extensions.json"), "utf8"), inventory);
assertExtensionSetReady();
const manifest = join(paths.extensions, "extensions.json");
renameSync(manifest, `${manifest}.held`);
assert.throws(assertExtensionSetReadable, /inventory is missing.*cotal ext seed --repair/);
renameSync(`${manifest}.held`, manifest);
renameSync(paths.ready, `${paths.ready}.held`);
assert.throws(assertExtensionSetReadable, /missing or incomplete.*cotal ext seed --repair/);
renameSync(`${paths.ready}.held`, paths.ready);
assertExtensionSetReadable();
writeFileSync(paths.ready, "{broken");
await prepareExtensionSet(async () => {
  assert.equal(readFileSync(manifest, "utf8"), inventory);
}, { repair: true });
assertExtensionSetReady();
const release = holdExtensionSet();
const releaseSecond = holdExtensionSet();
assert(extensionSetCleanupSpec().holders.some(holder => holder.version === paths.version && holder.state === "live"));
release(); release();
assert(extensionSetCleanupSpec().holders.some(holder => holder.version === paths.version && holder.state === "live"));
releaseSecond();
assert.equal(extensionSetCleanupSpec().holders.length, 0);
console.log("extension set paths: stable pnpm root, distinct installs, absent refusal, interrupted migration retry, legacy bytes and live PID/start holder passed");
